"""Generate the EaaS v3 baseline schema scripts from the authoritative v3 data dictionary.

Usage (from the repository root):

    python build/scripts/eaas-schema/generate_eaas_v3_schema.py

Input:  schema/eaas-v3/GDS_ComplianceIQ_Data_Dictionary_v3.csv (pipe-delimited, copied verbatim
        from toby67maro/Documents EaaS/ at commit f10e83b).
Output: src/EngineeringWorkspace.Infrastructure/Persistence/Schema/SqlServer/V0001__eaas_v3_baseline.sql
        src/EngineeringWorkspace.Infrastructure/Persistence/Schema/Sqlite/V0001__eaas_v3_baseline.sql
        src/EngineeringWorkspace.Infrastructure/Persistence/Schema/eaas-v3-schema-manifest.json

Derivation rules (documented in docs/architecture/eaas-v3-database-analysis.md):
  * Tables marked "Removed" in the V3Change column are not created.
  * Primary-key columns are NOT NULL. The dictionary records no other nullability, so every other
    column is NULL; nothing is tightened beyond what v3 states.
  * A single-column integer primary key that is not also a foreign key is a surrogate key and is
    generated by the database (IDENTITY(1,1) on SQL Server, INTEGER PRIMARY KEY on SQLite), following
    the v3 statement "surrogate keys, natural keys UNIQUE".
  * Columns flagged IsUniqueKeyPart form one natural-key UNIQUE constraint per table. Because those
    columns are nullable, SQL Server uses a filtered unique index (all parts IS NOT NULL); SQLite's
    UNIQUE constraint already ignores NULLs.
  * Columns flagged IsIndexed receive a non-unique index.
  * Foreign keys reference the single-column primary key of the target table. A foreign key whose
    column type differs from the referenced key type cannot be created by SQL Server; it is skipped
    and listed in the manifest as a conflict.
  * TemporalHistory = Y becomes a SQL Server system-versioned temporal table with hidden ValidFrom /
    ValidTo period columns and a <Table>History table in the same schema. SQLite has no equivalent.
  * Every statement is guarded (IF ... IS NULL / IF NOT EXISTS) so the script is repeatable and never
    drops, alters or overwrites an existing object.
"""

from __future__ import annotations

import csv
import hashlib
import json
import re
import sys
from collections import OrderedDict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
DICTIONARY = ROOT / "schema" / "eaas-v3" / "GDS_ComplianceIQ_Data_Dictionary_v3.csv"
OUTPUT = ROOT / "src" / "EngineeringWorkspace.Infrastructure" / "Persistence" / "Schema"
INTEGER_TYPES = {"int", "bigint", "smallint", "tinyint"}


def load_tables() -> "OrderedDict[str, list[dict[str, str]]]":
    with DICTIONARY.open(encoding="utf-8-sig", newline="") as handle:
        rows = list(csv.DictReader(handle, delimiter="|"))
    tables: "OrderedDict[str, list[dict[str, str]]]" = OrderedDict()
    for row in rows:
        if row["V3Change"].strip() == "Removed":
            continue
        tables.setdefault(f"{row['Schema']}.{row['Table']}", []).append(row)
    for columns in tables.values():
        columns.sort(key=lambda column: int(column["ColumnOrdinal"]))
    return tables


def primary_key(columns: list[dict[str, str]]) -> list[dict[str, str]]:
    return [column for column in columns if column["IsPrimaryKey"] == "Y"]


def is_identity(columns: list[dict[str, str]]) -> bool:
    keys = primary_key(columns)
    return len(keys) == 1 and keys[0]["DataType"] in INTEGER_TYPES and keys[0]["IsForeignKey"] != "Y"


def foreign_keys(tables, name):
    resolved, conflicts = [], []
    for column in tables[name]:
        if column["IsForeignKey"] != "Y":
            continue
        target = column["ForeignKeyTarget"]
        target_keys = primary_key(tables[target])
        if len(target_keys) != 1:
            conflicts.append({"table": name, "column": column["ColumnName"], "target": target,
                              "reason": "target table does not have a single-column primary key"})
            continue
        if target_keys[0]["DataType"] != column["DataType"]:
            conflicts.append({"table": name, "column": column["ColumnName"], "target": target,
                              "reason": f"column type {column['DataType']} differs from referenced key type "
                                        f"{target_keys[0]['DataType']}"})
            continue
        resolved.append((column["ColumnName"], target, target_keys[0]["ColumnName"]))
    return resolved, conflicts


def sqlserver_type(data_type: str) -> str:
    match = re.fullmatch(r"(\w+)(\((.+)\))?", data_type)
    base, size = match.group(1), match.group(3)
    return f"{base.upper()}({size.upper()})" if size else base.upper()


def sqlite_type(data_type: str) -> str:
    base = data_type.split("(")[0]
    if base in INTEGER_TYPES or base == "bit":
        return "INTEGER"
    if base in {"decimal", "numeric"}:
        return "NUMERIC"
    if base in {"float", "real"}:
        return "REAL"
    if base == "varbinary":
        return "BLOB"
    return "TEXT"


def split(name: str) -> tuple[str, str]:
    schema, table = name.split(".", 1)
    return schema, table


def generate_sqlserver(tables, conflicts_out) -> str:
    lines = [
        "-- EaaS v3 baseline schema for SQL Server 2022 / Azure SQL.",
        "-- GENERATED by build/scripts/eaas-schema/generate_eaas_v3_schema.py from",
        "-- schema/eaas-v3/GDS_ComplianceIQ_Data_Dictionary_v3.csv. Do not edit by hand.",
        "-- Repeatable: every statement is guarded and never drops or alters existing objects.",
        "",
    ]
    for schema in sorted({split(name)[0] for name in tables}):
        lines += [f"IF SCHEMA_ID(N'{schema}') IS NULL EXEC(N'CREATE SCHEMA [{schema}] AUTHORIZATION [dbo]');", "GO"]
    for name, columns in tables.items():
        schema, table = split(name)
        keys = primary_key(columns)
        temporal = columns[0]["TemporalHistory"] == "Y"
        definitions = []
        identity = is_identity(columns)
        for column in columns:
            null = "NOT NULL" if column["IsPrimaryKey"] == "Y" else "NULL"
            extra = " IDENTITY(1,1)" if identity and column["IsPrimaryKey"] == "Y" else ""
            definitions.append(f"    [{column['ColumnName']}] {sqlserver_type(column['DataType'])}{extra} {null}")
        if temporal:
            definitions.append("    [ValidFrom] DATETIME2 GENERATED ALWAYS AS ROW START HIDDEN NOT NULL")
            definitions.append("    [ValidTo] DATETIME2 GENERATED ALWAYS AS ROW END HIDDEN NOT NULL")
            definitions.append("    PERIOD FOR SYSTEM_TIME ([ValidFrom], [ValidTo])")
        key_list = ", ".join(f"[{key['ColumnName']}]" for key in keys)
        definitions.append(f"    CONSTRAINT [PK_{table}] PRIMARY KEY CLUSTERED ({key_list})")
        options = f"\nWITH (SYSTEM_VERSIONING = ON (HISTORY_TABLE = [{schema}].[{table}History]))" if temporal else ""
        lines += [
            f"IF OBJECT_ID(N'[{schema}].[{table}]', N'U') IS NULL",
            f"CREATE TABLE [{schema}].[{table}] (",
            ",\n".join(definitions),
            f"){options};",
            "GO",
        ]
    for name, columns in tables.items():
        schema, table = split(name)
        resolved, conflicts = foreign_keys(tables, name)
        conflicts_out.extend(conflicts)
        for column, target, target_key in resolved:
            target_schema, target_table = split(target)
            constraint = f"FK_{table}_{column}"
            lines += [
                f"IF OBJECT_ID(N'[{schema}].[{constraint}]', N'F') IS NULL",
                f"    ALTER TABLE [{schema}].[{table}] ADD CONSTRAINT [{constraint}] FOREIGN KEY ([{column}])"
                f" REFERENCES [{target_schema}].[{target_table}] ([{target_key}]);",
                "GO",
            ]
        unique = [column["ColumnName"] for column in columns if column["IsUniqueKeyPart"] == "Y"]
        if unique:
            index = f"UX_{table}_NaturalKey"
            column_list = ", ".join(f"[{column}]" for column in unique)
            predicate = " AND ".join(f"[{column}] IS NOT NULL" for column in unique)
            lines += [
                f"IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'{index}' AND object_id = OBJECT_ID(N'[{schema}].[{table}]'))",
                f"    CREATE UNIQUE NONCLUSTERED INDEX [{index}] ON [{schema}].[{table}] ({column_list}) WHERE {predicate};",
                "GO",
            ]
        for column in columns:
            if column["IsIndexed"] != "Y":
                continue
            index = f"IX_{table}_{column['ColumnName']}"
            lines += [
                f"IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'{index}' AND object_id = OBJECT_ID(N'[{schema}].[{table}]'))",
                f"    CREATE NONCLUSTERED INDEX [{index}] ON [{schema}].[{table}] ([{column['ColumnName']}]);",
                "GO",
            ]
    return "\n".join(lines) + "\n"


def generate_sqlite(tables) -> str:
    lines = [
        "-- EaaS v3 baseline schema adapted for SQLite (SECURE PLUS EXTENSION provider).",
        "-- GENERATED by build/scripts/eaas-schema/generate_eaas_v3_schema.py from",
        "-- schema/eaas-v3/GDS_ComplianceIQ_Data_Dictionary_v3.csv. Do not edit by hand.",
        "-- SQLite has no schemas, so v3 tables are named \"schema.Table\". Temporal history is not available.",
        "",
    ]
    for name, columns in tables.items():
        keys = primary_key(columns)
        identity = is_identity(columns)
        definitions = []
        for column in columns:
            if identity and column["IsPrimaryKey"] == "Y":
                definitions.append(f"    \"{column['ColumnName']}\" INTEGER PRIMARY KEY")
                continue
            null = " NOT NULL" if column["IsPrimaryKey"] == "Y" else ""
            definitions.append(f"    \"{column['ColumnName']}\" {sqlite_type(column['DataType'])}{null}")
        if not identity:
            definitions.append("    PRIMARY KEY (" + ", ".join(f"\"{key['ColumnName']}\"" for key in keys) + ")")
        unique = [column["ColumnName"] for column in columns if column["IsUniqueKeyPart"] == "Y"]
        if unique:
            definitions.append("    UNIQUE (" + ", ".join(f"\"{column}\"" for column in unique) + ")")
        resolved, _ = foreign_keys(tables, name)
        for column, target, target_key in resolved:
            definitions.append(f"    FOREIGN KEY (\"{column}\") REFERENCES \"{target}\" (\"{target_key}\")")
        lines += [f"CREATE TABLE IF NOT EXISTS \"{name}\" (", ",\n".join(definitions), ");", "GO"]
    for name, columns in tables.items():
        table = split(name)[1]
        for column in columns:
            if column["IsIndexed"] == "Y":
                lines += [f"CREATE INDEX IF NOT EXISTS \"IX_{table}_{column['ColumnName']}\" ON \"{name}\" (\"{column['ColumnName']}\");", "GO"]
    return "\n".join(lines) + "\n"


def main() -> int:
    tables = load_tables()
    conflicts: list[dict[str, str]] = []
    sqlserver = generate_sqlserver(tables, conflicts)
    sqlite = generate_sqlite(tables)
    (OUTPUT / "SqlServer").mkdir(parents=True, exist_ok=True)
    (OUTPUT / "Sqlite").mkdir(parents=True, exist_ok=True)
    (OUTPUT / "SqlServer" / "V0001__eaas_v3_baseline.sql").write_text(sqlserver, encoding="utf-8", newline="\n")
    (OUTPUT / "Sqlite" / "V0001__eaas_v3_baseline.sql").write_text(sqlite, encoding="utf-8", newline="\n")
    manifest = {
        "source": "schema/eaas-v3/GDS_ComplianceIQ_Data_Dictionary_v3.csv",
        "sourceSha256": hashlib.sha256(DICTIONARY.read_bytes()).hexdigest(),
        "tableCount": len(tables),
        "columnCount": sum(len(columns) for columns in tables.values()),
        "foreignKeyConflicts": conflicts,
        "tables": [
            {
                "schema": split(name)[0],
                "name": split(name)[1],
                "temporal": columns[0]["TemporalHistory"] == "Y",
                "columns": [column["ColumnName"] for column in columns],
            }
            for name, columns in tables.items()
        ],
    }
    (OUTPUT / "eaas-v3-schema-manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8", newline="\n")
    print(f"Generated {len(tables)} tables; {len(conflicts)} foreign-key conflict(s).")
    for conflict in conflicts:
        print(f"  CONFLICT {conflict['table']}.{conflict['column']} -> {conflict['target']}: {conflict['reason']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
