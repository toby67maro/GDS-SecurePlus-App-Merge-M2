#!/usr/bin/env python3
"""Writes docs/DATA_COVERAGE.md from the EaaS v3 data dictionary, the Secure Plus migrations and the classification in
src/EngineeringWorkspace.Application/Database/DataCoverage.cs (the same rules the Database Health page uses).

Usage: python3 build/scripts/knowledge/generate_data_coverage.py --dictionary /path/to/Documents/EaaS/GDS_ComplianceIQ_Data_Dictionary_v3.csv
"""
import argparse
import collections
import glob
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
ORDER = ["SecurePlus", "SecurePlusSeed", "EaasKnowledgeBase", "EaasOtherComponent"]
NAMES = {"SecurePlus": "Secure Plus (when used)", "SecurePlusSeed": "Secure Plus (installer seed / knowledge base)",
         "EaasKnowledgeBase": "Knowledge base, later phase", "EaasOtherComponent": "Other EaaS component"}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--dictionary", required=True)
    args = parser.parse_args()
    source = open(os.path.join(ROOT, "src/EngineeringWorkspace.Application/Database/DataCoverage.cs"), encoding="utf-8").read()
    tables = {key: (owner, purpose) for key, owner, purpose in re.findall(r'\["(\w+\.\w+)"\] = \(DataOwner\.(\w+), "([^"]*)"\)', source)}
    schemas = {key: (owner, purpose) for key, owner, purpose in re.findall(r'\["(\w+)"\] = \(DataOwner\.(\w+), "([^"]*)"\)', source)}
    rows = collections.OrderedDict()
    for line in open(args.dictionary, encoding="utf-8-sig").read().splitlines()[1:]:
        parts = line.split("|")
        if not parts[2].startswith("Removed in v3"):
            rows.setdefault(f"{parts[0]}.{parts[1]}", parts[2])
    for path in glob.glob(os.path.join(ROOT, "src/EngineeringWorkspace.Infrastructure/Persistence/Schema/SqlServer/*.sql")):
        for match in re.finditer(r"CREATE TABLE \[secureplus\]\.\[(\w+)\]", open(path, encoding="utf-8").read()):
            rows.setdefault(f"secureplus.{match.group(1)}", "Secure Plus extension table.")

    def classify(table):
        return tables.get(table) or schemas.get(table.split(".")[0], ("EaasOtherComponent", ""))

    counts = collections.Counter(classify(table)[0] for table in rows)
    out = ["# Data Coverage of the SecurePlus Database", "",
           "Which component fills each table of the SecurePlus database (EaaS v3 schema plus the Secure Plus `secureplus` extension).",
           "The same classification drives **Settings > Database Health > Data Coverage**, which adds live row counts;",
           "`scripts/sql/Audit-SecurePlusDatabase.sql` produces row counts and column fill rates on any SQL Server without the application.",
           "Generated by `build/scripts/knowledge/generate_data_coverage.py`.", "", "## Summary", "", "| Filled by | Tables |", "|---|---|"]
    out += [f"| {NAMES[owner]} | {counts[owner]} |" for owner in ORDER]
    out += ["", f"Total: {len(rows)} tables.", "",
            "**Knowledge base (2.2–2.4).** Phase 1 loads the Secure Controls Framework 2026.3 with its 270 focal documents and 76,019 mappings,",
            "NIST SP 800-53 Rev 5 / 800-53A and MITRE ATT&CK. Phase 2 loads 56 CIS Benchmarks and 3 Microsoft security baselines, the Secure Plus",
            "WBS, the discovery decisions and EaaS question bank, and the deployment method matrix. Phase 3 loads Microsoft licensing (SKUs and",
            "service plans), MITRE CTID threat coverage, the service tiers, the Customer Deployment Checklist, configuration changes, known",
            "issues and guidance from the catalog, baseline deltas, cross-baseline relations and procedures, experience expectations, rings,",
            "framework attributes and scope categories, and the scoring model with enrichment values and item scores. After each assessment",
            "Secure Plus also writes findings, derived requirement results, score and observation snapshots. Tables of *other EaaS components*",
            "belong to features not built yet (estimates and project plans, SOW, specifications and approvals, drift comparison, PSA, forms).", "",
            "## Every table", "", "| Table | Filled by | Purpose |", "|---|---|---|"]
    for table, description in sorted(rows.items(), key=lambda item: (ORDER.index(classify(item[0])[0]), item[0])):
        owner, purpose = classify(table)
        text = purpose if table in tables else description.replace("|", "/")
        out.append(f"| `{table}` | {NAMES[owner]} | {text[:170]} |")
    with open(os.path.join(ROOT, "docs/DATA_COVERAGE.md"), "w", encoding="utf-8") as handle:
        handle.write("\n".join(out) + "\n")
    print(dict(counts), len(rows))


if __name__ == "__main__":
    main()
