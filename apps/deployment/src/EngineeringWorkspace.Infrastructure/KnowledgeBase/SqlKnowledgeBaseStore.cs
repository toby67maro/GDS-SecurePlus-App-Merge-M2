/// <summary>The knowledge base generated by build/scripts/knowledge/generate_knowledge_base.py and embedded as knowledge-base.json.gz.</summary>
public sealed class EmbeddedKnowledgeBase
{
    public const string ResourceName = "EngineeringWorkspace.KnowledgeBase.knowledge-base.json.gz";
    public const string BaselinesResourceName = "EngineeringWorkspace.KnowledgeBase.baselines.json.gz";
    private static readonly Lazy<EmbeddedKnowledgeBase> Instance = new(() => LoadEmbedded(ResourceName));
    private static readonly Lazy<EmbeddedKnowledgeBase> BaselinesInstance = new(() => LoadEmbedded(BaselinesResourceName));
    public const string Phase3ResourceName = "EngineeringWorkspace.KnowledgeBase.knowledge-base-phase3.json.gz";
    private static readonly Lazy<EmbeddedKnowledgeBase> Phase3Instance = new(() => LoadEmbedded(Phase3ResourceName));

    /// <summary>Phase 3: licensing, CTID threat coverage, service tiers, checklist, configuration changes, scoring and enrichment.</summary>
    public static EmbeddedKnowledgeBase Phase3 => Phase3Instance.Value;

    private EmbeddedKnowledgeBase(JsonDocument document, string hash)
    {
        Document = document;
        Hash = hash;
        Version = document.RootElement.GetProperty("version").GetString()!;
    }

    public JsonDocument Document { get; }
    public string Hash { get; }
    public string Version { get; }
    public JsonElement Root => Document.RootElement;

    /// <summary>Phase 1: SCF, NIST SP 800-53 / 800-53A, MITRE ATT&amp;CK.</summary>
    public static EmbeddedKnowledgeBase Current => Instance.Value;

    /// <summary>Phase 2: CIS Benchmarks, Microsoft security baselines, GDS WBS and question bank, deployment method matrix.</summary>
    public static EmbeddedKnowledgeBase Baselines => BaselinesInstance.Value;

    public IEnumerable<JsonElement> Rows(string name) => Root.TryGetProperty(name, out var array) ? array.EnumerateArray() : [];
    public int Count(string name) => Root.TryGetProperty(name, out var array) ? array.GetArrayLength() : 0;

    /// <summary>Loads another embedded knowledge-base part by resource name.</summary>
    public static EmbeddedKnowledgeBase Load(string resourceName) => LoadEmbedded(resourceName);

    private static EmbeddedKnowledgeBase LoadEmbedded(string resourceName)
    {
        using var stream = typeof(EmbeddedKnowledgeBase).Assembly.GetManifestResourceStream(resourceName)
                           ?? throw new InvalidOperationException($"The embedded knowledge base {resourceName} is missing from the build.");
        using var gzip = new GZipStream(stream, CompressionMode.Decompress);
        using var buffer = new MemoryStream();
        gzip.CopyTo(buffer);
        var bytes = buffer.ToArray();
        return new EmbeddedKnowledgeBase(JsonDocument.Parse(bytes), Convert.ToHexString(SHA256.HashData(bytes)).ToLowerInvariant());
    }
}

/// <summary>
/// Loads the knowledge base into the EaaS v3 tables in one transaction. Reference rows (frameworks, versions,
/// requirements, domains, profiles, assessment objectives, evidence artifacts, risks, threats, ATT&amp;CK tactics,
/// techniques and mitigations) are upserted by their natural keys and never deleted, so other data that refers to them
/// stays valid. Link rows the knowledge base owns (SCF mappings, control attributes, lineage, compensating controls,
/// maturity criteria, profile members, evidence links, risk/threat likelihoods, technique links) are replaced.
/// Recorded as dataset "knowledge-base" in secureplus.SeedVersion with the content hash.
/// </summary>
public sealed class SqlKnowledgeBaseStore(IDatabaseStatusService database, DatabaseConnectionFactory connections, TimeProvider timeProvider) : IKnowledgeBaseStore
{
    public const string Dataset = "knowledge-base";
    private const string PendingAliases = "+pending-catalog";

    public bool IsAvailable => database.Settings.Provider != DatabaseProvider.None && database.LatestStatus?.State == DatabaseOverallState.Ready;

    public async Task<KnowledgeBaseState> GetStateAsync(CancellationToken cancellationToken = default)
    {
        var embedded = EmbeddedKnowledgeBase.Current;
        await using var session = await OpenAsync(cancellationToken);
        var row = (await QueryAsync(session, null, $"SELECT Version, ContentHash, AppliedAtUtc, Summary FROM {session.Table("secureplus", "SeedVersion")} WHERE Dataset = @dataset;",
            Parameters(("@dataset", Dataset)), cancellationToken)).FirstOrDefault();
        return new KnowledgeBaseState(embedded.Version, embedded.Hash, row?["Version"] as string, row?["ContentHash"] as string,
            row?["AppliedAtUtc"] is { } at ? SqlSession.ReadDate(at) : null, row?["Summary"] as string);
    }

    public async Task<KnowledgeBaseLoadResult> LoadAsync(bool force, IProgress<(double Progress, string Activity)>? progress, CancellationToken cancellationToken = default)
    {
        var kb = EmbeddedKnowledgeBase.Current;
        var started = Stopwatch.StartNew();
        if (!force && (await GetStateAsync(cancellationToken)).IsCurrent)
            return new KnowledgeBaseLoadResult(true, kb.Version, new Dictionary<string, int>(), started.Elapsed);

        await using var session = await OpenAsync(cancellationToken);
        session.CommandTimeoutSeconds = Math.Max(session.CommandTimeoutSeconds, 600);
        await using var transaction = await session.Connection.BeginTransactionAsync(IsolationLevel.ReadCommitted, cancellationToken);
        var counts = new Dictionary<string, int>(StringComparer.Ordinal);
        var loader = new Loader(session, transaction, counts, cancellationToken);
        void Report(double percent, string activity) => progress?.Report((percent, activity));

        // ----- Reference values the knowledge base depends on -----
        Report(2, "Writing mapping sources and rating scales...");
        var sources = await loader.UpsertAsync("ref", "MappingSource", "MappingSourceId", ["Code"], ["Name", "Publisher", "AuthorityLevelCode", "DefaultConfidence", "Url"],
            kb.Rows("mappingSources").Select(row => new object?[] { S(row, "code"), S(row, "name"), S(row, "publisher"), S(row, "authority"), I(row, "confidence"), S(row, "url") }));
        var relationships = await loader.UpsertAsync("ref", "RelationshipType", "RelationshipTypeId", ["Code"], ["Name", "CountsAsSatisfies", "Description"],
            EaasReferenceData.RelationshipTypes.Select(type => new object?[] { type.Code, type.Name, session.Bool(type.CountsAsSatisfies), type.Description }), count: false);
        var maturityLevels = await loader.UpsertAsync("ref", "MaturityLevel", "MaturityLevelId", ["Code"], ["Name", "Description"],
            EaasReferenceData.MaturityLevels.Select(level => new object?[] { level.Code, level.Name, level.Description }), count: false);
        var scales = await loader.UpsertAsync("ref", "RatingScale", "RatingScaleId", ["Code"], ["Name", "MinValue", "MaxValue", "HigherIsWorse", "Description"],
            kb.Rows("ratingScales").Select(row => new object?[] { S(row, "code"), S(row, "name"), D(row, "min"), D(row, "max"), session.Bool(row.GetProperty("higherIsWorse").GetBoolean()),
                S(row, "description") }));
        var scaleValueRows = kb.Rows("ratingScales").SelectMany(scale => scale.GetProperty("values").EnumerateArray().Select(value => new object?[]
        {
            scales[S(scale, "code")!], Sx(value, 1), Dx(value, 0), Dx(value, 2), Dx(value, 3), Sx(value, 4), null
        }));
        var scaleValues = await loader.UpsertAsync("ref", "RatingScaleValue", "RatingScaleValueId", ["RatingScaleId", "Label"], ["NumericValue", "BinLow", "BinHigh", "ColorHex", "Description"],
            scaleValueRows);
        var likelihood = scaleValues.Where(pair => pair.Key.StartsWith($"{scales["SCF-LIKELIHOOD"]}\u001f", StringComparison.Ordinal))
            .ToDictionary(pair => pair.Key.Split('\u001f')[1], pair => pair.Value, StringComparer.OrdinalIgnoreCase);

        // ----- Frameworks, versions, requirements -----
        Report(6, "Writing 271 frameworks...");
        var frameworkRows = kb.Rows("frameworks").ToArray();
        var frameworks = await loader.UpsertAsync("fw", "Framework", "FrameworkId", ["Code"],
            ["Name", "ShortName", "Publisher", "FrameworkTypeCode", "GeographyCode", "Jurisdiction", "IsHub", "ScfFocalDocumentId", "ScfColumnHeader", "Url", "StrmUrl", "Description"],
            frameworkRows.Select(row => new object?[]
            {
                S(row, "code"), S(row, "name"), S(row, "short"), S(row, "publisher"), S(row, "type"), S(row, "geography"), S(row, "jurisdiction"),
                session.Bool(row.GetProperty("isHub").GetBoolean()), S(row, "fdi"), S(row, "column"), S(row, "url"), S(row, "strmUrl"), S(row, "description")
            }));
        var requirementCounts = kb.Rows("requirements").GroupBy(row => row[0].GetString()!).ToDictionary(group => group.Key, group => group.Count());
        var versions = await loader.UpsertAsync("fw", "FrameworkVersion", "FrameworkVersionId", ["FrameworkId", "VersionLabel"],
            ["LifecycleStatusCode", "HasFullText", "RequirementCount", "Notes"],
            frameworkRows.Select(row => new object?[]
            {
                frameworks[S(row, "code")!], S(row, "version"), "Current", session.Bool(row.GetProperty("hasFullText").GetBoolean()),
                requirementCounts.GetValueOrDefault(S(row, "code")!), $"Loaded from the Secure Plus knowledge base {kb.Version}."
            }));
        var versionOf = frameworkRows.ToDictionary(row => S(row, "code")!, row => versions[Key(frameworks[S(row, "code")!], S(row, "version"))], StringComparer.Ordinal);

        Report(10, $"Writing {kb.Count("requirements"):N0} requirements...");
        var requirementRows = kb.Rows("requirements").ToArray();
        var requirements = await loader.UpsertAsync("fw", "Requirement", "RequirementId", ["FrameworkVersionId", "RequirementCode"],
            ["MatchKey", "SortKey", "HierarchyLevelCode", "Title", "Statement", "Discussion", "RequirementTypeCode", "IsAssessable", "IsStub", "IsNewInVersion", "IsWithdrawn", "SourceRowRef"],
            requirementRows.Select(row => new object?[]
            {
                versionOf[row[0].GetString()!], row[1].GetString(), Sx(row, 2), Sx(row, 3), Sx(row, 4), Sx(row, 5), Sx(row, 6), Sx(row, 7), "Requirement",
                session.Bool(!row[8].GetBoolean()), session.Bool(row[8].GetBoolean()), session.Bool(false), session.Bool(false), $"knowledge-base {kb.Version}"
            }));
        int Requirement(string framework, string code) => requirements[Key(versionOf[framework], code)];
        bool HasRequirement(string framework, string code) => versionOf.TryGetValue(framework, out var version) && requirements.ContainsKey(Key(version, code));

        var parents = requirementRows.Where(row => row[9].ValueKind == JsonValueKind.String && HasRequirement(row[0].GetString()!, row[9].GetString()!))
            .Select(row => new object?[] { Requirement(row[0].GetString()!, row[9].GetString()!), Requirement(row[0].GetString()!, row[1].GetString()!) }).ToList();
        await BulkUpdateAsync(session, transaction, session.Table("fw", "Requirement"), ["RequirementId"], ["ParentRequirementId"], parents, cancellationToken);

        // ----- SCF crosswalk and catalog aliases -----
        Report(30, $"Writing {kb.Count("maps"):N0} SCF mappings...");
        var intersects = relationships["IntersectsWith"];
        var equal = relationships["Equal"];
        var scfSource = sources["SCF-STRM"];
        var aliasSource = sources["GDS-ALIAS"];
        await loader.ReplaceAsync("fw", "RequirementMap", $"MappingSourceId IN ({scfSource}, {aliasSource})",
            ["FromRequirementId", "ToRequirementId", "RelationshipTypeId", "MappingSourceId", "ConfidenceCode", "Rationale", "IsDerived"],
            kb.Rows("maps").Where(row => HasRequirement(row[0].GetString()!, row[1].GetString()!) && HasRequirement(row[2].GetString()!, row[3].GetString()!))
                .Select(row => new object?[]
                {
                    Requirement(row[0].GetString()!, row[1].GetString()!), Requirement(row[2].GetString()!, row[3].GetString()!), intersects, scfSource, "Medium",
                    "SCF 2026.3 mapping column (the workbook does not state the STRM relationship type).", session.Bool(false)
                }));
        var catalogRequirements = await CatalogRequirementsAsync(session, transaction, cancellationToken);
        var aliasRows = new List<object?[]>();
        var pendingAliases = 0;
        foreach (var alias in kb.Rows("aliases"))
        {
            var catalogKey = $"{alias[0].GetString()}\u001f{alias[1].GetString()}\u001f{alias[2].GetString()}";
            if (!catalogRequirements.TryGetValue(catalogKey, out var catalogRequirement) || !HasRequirement(alias[3].GetString()!, alias[4].GetString()!))
            {
                pendingAliases++;
                continue;
            }

            aliasRows.Add([catalogRequirement, Requirement(alias[3].GetString()!, alias[4].GetString()!), equal, aliasSource, "High",
                "The Secure Plus catalog reference and the SCF focal document requirement are the same requirement.", session.Bool(false)]);
        }

        await BulkInsertAsync(session, transaction, session.Table("fw", "RequirementMap"),
            ["FromRequirementId", "ToRequirementId", "RelationshipTypeId", "MappingSourceId", "ConfidenceCode", "Rationale", "IsDerived"], aliasRows, null, cancellationToken);
        counts["fw.RequirementMap"] += aliasRows.Count;

        // ----- SCF domains, controls, lineage, compensating controls, maturity, profiles -----
        Report(38, "Writing SCF domains and control attributes...");
        var domains = await loader.UpsertAsync("fw", "ScfDomain", "ScfDomainId", ["Code"], ["Name", "Principle", "PrincipleIntent", "SortOrder"],
            kb.Rows("domains").Select(row => new object?[] { Sx(row, 0), Sx(row, 1), Sx(row, 2), Sx(row, 3), Ix(row, 4) }));
        int Scf(string code) => Requirement("scf", code);
        await loader.ReplaceAsync("fw", "ScfControl", null,
            ["RequirementId", "ScfDomainId", "ControlWeight", "ValidationCadence", "ErlCodes", "PPTDF_People", "PPTDF_Process", "PPTDF_Technology", "PPTDF_Data", "PPTDF_Facility",
             "CsfFunctionCode", "ScrmTier1", "ScrmTier2", "ScrmTier3", "ControlQuestion", "RiskIfNotImplemented", "SolutionsMicroSmall", "SolutionsSmall", "SolutionsMedium",
             "SolutionsLarge", "SolutionsEnterprise", "IsOrphaned", "LegacyScfCode", "Errata"],
            kb.Rows("scfControls").Where(row => HasRequirement("scf", S(row, "code")!)).Select(row => new object?[]
            {
                Scf(S(row, "code")!), S(row, "domain") is { } domain && domains.TryGetValue(domain, out var domainId) ? domainId : null, I(row, "weight"), S(row, "cadence"),
                S(row, "erl"), Flag(session, row, "people"), Flag(session, row, "process"), Flag(session, row, "technology"), Flag(session, row, "data"), Flag(session, row, "facility"),
                S(row, "csf"), Flag(session, row, "tier1"), Flag(session, row, "tier2"), Flag(session, row, "tier3"), S(row, "question"), S(row, "risk"), S(row, "micro"),
                S(row, "small"), S(row, "medium"), S(row, "large"), S(row, "enterprise"), Flag(session, row, "orphaned"), S(row, "legacy"), S(row, "errata")
            }));
        await loader.ReplaceAsync("fw", "ScfControlLineage", null, ["RequirementId", "LegacyScfCode", "ChangeTypeCode", "Note"],
            kb.Rows("lineage").Where(row => HasRequirement("scf", Sx(row, 0)!)).Select(row => new object?[] { Scf(Sx(row, 0)!), Sx(row, 1), Sx(row, 2), Sx(row, 3) }));
        await loader.ReplaceAsync("fw", "CompensatingControl", null, ["RequirementId", "Sequence", "CompensatingRequirementId", "Name", "Description", "Justification"],
            kb.Rows("compensating").Where(row => HasRequirement("scf", Sx(row, 0)!)).Select(row => new object?[]
            {
                Scf(Sx(row, 0)!), Ix(row, 1), Sx(row, 2) is { } code && HasRequirement("scf", code) ? Scf(code) : null, Sx(row, 3), Sx(row, 4), Sx(row, 5)
            }));
        await loader.ReplaceAsync("fw", "MaturityCriterion", null, ["RequirementId", "MaturityLevelId", "CriterionText"],
            kb.Rows("maturity").Where(row => HasRequirement("scf", Sx(row, 0)!)).Select(row => new object?[] { Scf(Sx(row, 0)!), maturityLevels[Sx(row, 1)!], Sx(row, 2) }));
        var profileRows = kb.Rows("profiles").ToArray();
        var profiles = await loader.UpsertAsync("fw", "Profile", "ProfileId", ["FrameworkVersionId", "Code"], ["Name", "ProfileTypeCode", "IsCumulative", "Description"],
            profileRows.Select(row => new object?[]
                { versionOf[S(row, "framework")!], S(row, "code"), S(row, "name"), S(row, "type"), session.Bool(false), $"SCF 2026.3 column '{S(row, "name")}'." }));
        var profileIds = profileRows.Select(row => profiles[Key(versionOf[S(row, "framework")!], S(row, "code"))]).ToArray();
        await loader.ReplaceAsync("fw", "ProfileRequirement", profileIds.Length == 0 ? "1 = 0" : $"ProfileId IN ({string.Join(", ", profileIds)})",
            ["ProfileId", "RequirementId", "IsInherited"],
            profileRows.SelectMany((row, index) => row.GetProperty("requirements").EnumerateArray().Where(code => HasRequirement(S(row, "framework")!, code.GetString()!))
                .Select(code => new object?[] { profileIds[index], Requirement(S(row, "framework")!, code.GetString()!), session.Bool(false) })));

        // ----- Assessment objectives and evidence -----
        Report(48, $"Writing {kb.Count("objectives"):N0} assessment objectives...");
        await loader.UpsertAsync("fw", "AssessmentObjective", "AssessmentObjectiveId", ["RequirementId", "ObjectiveCode"],
            ["ObjectiveText", "DefinedParameter", "PPTDF", "AssessmentRigor", "Origin", "ExamineText", "InterviewText", "TestText", "ExpectedResult", "SortKey"],
            kb.Rows("objectives").Where(row => HasRequirement(Sx(row, 0)!, Sx(row, 1)!)).Select(row => new object?[]
            {
                Requirement(Sx(row, 0)!, Sx(row, 1)!), Sx(row, 2), Sx(row, 4), Sx(row, 5), Sx(row, 6), Ix(row, 7), Sx(row, 8), Sx(row, 9), Sx(row, 10), Sx(row, 11), Sx(row, 12),
                Sx(row, 13)
            }), returnMap: false);
        var evidence = await loader.UpsertAsync("fw", "EvidenceArtifact", "EvidenceArtifactId", ["ErlCode"], ["AreaOfFocus", "ArtifactName", "ArtifactDescription", "RelevantCmmcL2"],
            kb.Rows("evidence").Select(row => new object?[] { Sx(row, 0), Sx(row, 1), Sx(row, 2), Sx(row, 3), Sx(row, 4) }));
        await loader.ReplaceAsync("fw", "RequirementEvidence", null, ["RequirementId", "EvidenceArtifactId", "MappingSourceId"],
            kb.Rows("requirementEvidence").Where(row => HasRequirement("scf", Sx(row, 0)!) && evidence.ContainsKey(Sx(row, 1)!))
                .Select(row => new object?[] { Scf(Sx(row, 0)!), evidence[Sx(row, 1)!], scfSource }));

        // ----- Risks and threats -----
        Report(60, "Writing the SCF risk and threat catalogs and their likelihood per control...");
        var risks = await loader.UpsertAsync("threat", "Risk", "RiskId", ["RiskCode"],
            ["RiskGrouping", "Name", "Description", "CsfFunctionCode", "MaterialityPretaxIncome", "MaterialityTotalAssets", "MaterialityTotalEquity", "MaterialityTotalRevenue"],
            kb.Rows("risks").Select(row => new object?[] { Sx(row, 0), Sx(row, 1), Sx(row, 2), Sx(row, 3), Sx(row, 4), Sx(row, 5), Sx(row, 6), Sx(row, 7), Sx(row, 8) }));
        var threats = await loader.UpsertAsync("threat", "Threat", "ThreatId", ["ThreatCode"],
            ["ThreatGrouping", "Name", "Description", "MaterialityPretaxIncome", "MaterialityTotalAssets", "MaterialityTotalEquity", "MaterialityTotalRevenue"],
            kb.Rows("threats").Select(row => new object?[] { Sx(row, 0), Sx(row, 1), Sx(row, 2), Sx(row, 3), Sx(row, 4), Sx(row, 5), Sx(row, 6), Sx(row, 7) }));
        await loader.ReplaceAsync("threat", "ControlRisk", null, ["RequirementId", "RiskId", "LikelihoodScaleValueId", "SourceLabel"],
            kb.Rows("controlRisks").Where(row => HasRequirement("scf", Sx(row, 0)!) && risks.ContainsKey(Sx(row, 1)!)).Select(row => new object?[]
                { Scf(Sx(row, 0)!), risks[Sx(row, 1)!], likelihood.TryGetValue(Sx(row, 2)!, out var value) ? value : null, Sx(row, 2) }));
        Report(72, "Writing threat likelihoods...");
        await loader.ReplaceAsync("threat", "ControlThreat", null, ["RequirementId", "ThreatId", "LikelihoodScaleValueId", "SourceLabel"],
            kb.Rows("controlThreats").Where(row => HasRequirement("scf", Sx(row, 0)!) && threats.ContainsKey(Sx(row, 1)!)).Select(row => new object?[]
                { Scf(Sx(row, 0)!), threats[Sx(row, 1)!], likelihood.TryGetValue(Sx(row, 2)!, out var value) ? value : null, Sx(row, 2) }));

        // ----- MITRE ATT&CK -----
        Report(84, "Writing MITRE ATT&CK tactics, techniques and mitigations...");
        var tactics = await loader.UpsertAsync("threat", "AttackTactic", "TacticId", ["TacticCode"], ["Name", "ShortDescription", "Description", "KillChainOrder", "Url"],
            kb.Rows("tactics").Select(row => new object?[] { Sx(row, 0), Sx(row, 1), Sx(row, 2), Sx(row, 3), Ix(row, 4), Sx(row, 5) }));
        var techniqueRows = kb.Rows("techniques").ToArray();
        var techniques = await loader.UpsertAsync("threat", "AttackTechnique", "TechniqueId", ["TechniqueCode"],
            ["Name", "IsSubTechnique", "Description", "DetectionStrategies", "Platforms", "AttackVersion", "IsDeprecated", "Url"],
            techniqueRows.Select(row => new object?[]
                { Sx(row, 0), Sx(row, 2), session.Bool(row[3].GetBoolean()), Sx(row, 4), Sx(row, 5), Sx(row, 6), Sx(row, 7), session.Bool(false), Sx(row, 8) }));
        await BulkUpdateAsync(session, transaction, session.Table("threat", "AttackTechnique"), ["TechniqueId"], ["ParentTechniqueId"],
            techniqueRows.Where(row => Sx(row, 1) is { } parent && techniques.ContainsKey(parent)).Select(row => new object?[] { techniques[Sx(row, 1)!], techniques[Sx(row, 0)!] }).ToList(),
            cancellationToken);
        await loader.ReplaceAsync("threat", "TechniqueTactic", null, ["TechniqueId", "TacticId"],
            kb.Rows("techniqueTactics").Where(row => techniques.ContainsKey(Sx(row, 0)!) && tactics.ContainsKey(Sx(row, 1)!))
                .Select(row => new object?[] { techniques[Sx(row, 0)!], tactics[Sx(row, 1)!] }));
        var mitigations = await loader.UpsertAsync("threat", "AttackMitigation", "MitigationId", ["MitigationCode"], ["Name", "Description", "Url"],
            kb.Rows("mitigations").Select(row => new object?[] { Sx(row, 0), Sx(row, 1), Sx(row, 2), Sx(row, 3) }));
        await loader.ReplaceAsync("threat", "TechniqueMitigation", null, ["TechniqueId", "MitigationId", "HowItApplies"],
            kb.Rows("techniqueMitigations").Where(row => techniques.ContainsKey(Sx(row, 0)!) && mitigations.ContainsKey(Sx(row, 1)!))
                .Select(row => new object?[] { techniques[Sx(row, 0)!], mitigations[Sx(row, 1)!], Sx(row, 2) }));
        await loader.ReplaceAsync("threat", "RequirementTechnique", $"MappingSourceId = {scfSource}",
            ["RequirementId", "TechniqueId", "MappingSourceId", "MappingCategoryCode", "AttackVersion"],
            kb.Rows("requirementTechniques").Where(row => HasRequirement("scf", Sx(row, 0)!) && techniques.ContainsKey(Sx(row, 1)!))
                .Select(row => new object?[] { Scf(Sx(row, 0)!), techniques[Sx(row, 1)!], scfSource, "SCF", "16" }));

        // ----- Record the version -----
        Report(97, "Recording the knowledge base version...");
        var summary = $"{kb.Version}: {counts.Values.Sum():N0} rows in {counts.Count} tables" +
                      (pendingAliases > 0 ? $"; {pendingAliases} catalog link(s) waiting for the catalog to be loaded" : string.Empty) + ".";
        await SqlReferenceSeedStore.UpsertVersionAsync(session, transaction, Dataset, kb.Version, pendingAliases > 0 ? CombineHashes(kb.Hash, PendingAliases) : kb.Hash, counts.Values.Sum(),
            timeProvider.GetUtcNow(), summary, cancellationToken);
        await transaction.CommitAsync(cancellationToken);
        Report(100, "The knowledge base is loaded.");
        return new KnowledgeBaseLoadResult(false, kb.Version, counts, started.Elapsed);
    }

    /// <summary>Requirements written by the catalog seed, keyed by framework code, version label and requirement code.</summary>
    private static async Task<Dictionary<string, int>> CatalogRequirementsAsync(SqlSession session, DbTransaction transaction, CancellationToken cancellationToken)
    {
        var rows = await QueryAsync(session, transaction,
            $"SELECT f.Code AS F, v.VersionLabel AS V, r.RequirementCode AS R, r.RequirementId AS Id FROM {session.Table("fw", "Requirement")} AS r " +
            $"JOIN {session.Table("fw", "FrameworkVersion")} AS v ON v.FrameworkVersionId = r.FrameworkVersionId JOIN {session.Table("fw", "Framework")} AS f ON f.FrameworkId = v.FrameworkId " +
            $"WHERE f.Code IN ('NIST-800-53', 'NIST-CSF', 'CIS-CONTROLS', 'ISO-27001', 'CMMC', 'PCI-DSS', 'HIPAA', 'ESSENTIAL-EIGHT');", null, cancellationToken);
        var map = new Dictionary<string, int>(KeyComparer);
        foreach (var row in rows) map[$"{row["F"]}\u001f{row["V"]}\u001f{row["R"]}"] = Convert.ToInt32(row["Id"], CultureInfo.InvariantCulture);
        return map;
    }

    internal static string? S(JsonElement row, string name) => row.TryGetProperty(name, out var value) && value.ValueKind == JsonValueKind.String ? value.GetString() : null;
    internal static int? I(JsonElement row, string name) => row.TryGetProperty(name, out var value) && value.ValueKind == JsonValueKind.Number ? value.GetInt32() : null;
    internal static decimal? D(JsonElement row, string name) => row.TryGetProperty(name, out var value) && value.ValueKind == JsonValueKind.Number ? value.GetDecimal() : null;
    internal static string? Sx(JsonElement row, int index) => row[index].ValueKind == JsonValueKind.String ? row[index].GetString() : null;
    internal static int? Ix(JsonElement row, int index) => row[index].ValueKind == JsonValueKind.Number ? (int)row[index].GetDecimal() : null;
    internal static decimal? Dx(JsonElement row, int index) => row[index].ValueKind == JsonValueKind.Number ? row[index].GetDecimal() : null;
    private static object Flag(SqlSession session, JsonElement row, string name) => session.Bool(row.TryGetProperty(name, out var value) && value.ValueKind == JsonValueKind.True);
    /// <summary>
    /// Natural key (parts joined with U+001F, trailing spaces removed). Compare keys with <see cref="KeyComparer"/>: SQL Server's
    /// default collation ignores case and trailing spaces, so the loader must treat such keys as one row on every provider.
    /// </summary>
    public static string Key(params object?[] parts) =>
        string.Join('\u001f', parts.Select(part => (Convert.ToString(part, CultureInfo.InvariantCulture) ?? string.Empty).TrimEnd()));

    public static readonly StringComparer KeyComparer = StringComparer.OrdinalIgnoreCase;

    /// <summary>One SHA-256 (64 hex characters, the size of secureplus.SeedVersion.ContentHash) of several version parts.</summary>
    public static string CombineHashes(params string[] parts) =>
        Convert.ToHexString(SHA256.HashData(System.Text.Encoding.UTF8.GetBytes(string.Join("|", parts)))).ToLowerInvariant();

    private Task<SqlSession> OpenAsync(CancellationToken cancellationToken) =>
        SqlSession.OpenAsync(database, connections, message => new InvalidOperationException(message), cancellationToken);

    /// <summary>Upserts by natural key and replaces link rows, counting rows per table.</summary>
    internal sealed class Loader(SqlSession session, DbTransaction transaction, Dictionary<string, int> counts, CancellationToken cancellationToken)
    {
        /// <summary>Inserts new keys, updates existing ones and returns key → ID (keys joined with U+001F).</summary>
        public async Task<Dictionary<string, int>> UpsertAsync(string schema, string table, string idColumn, string[] keys, string[] values, IEnumerable<object?[]> rows,
            bool count = true, bool returnMap = true)
        {
            var target = session.Table(schema, table);
            var existing = await MapAsync(target, idColumn, keys);
            var inserts = new List<object?[]>();
            var updates = new List<object?[]>();
            var seen = new HashSet<string>(KeyComparer);
            foreach (var row in rows)
            {
                var key = Key(row.Take(keys.Length).ToArray());
                if (!seen.Add(key)) continue;
                if (existing.ContainsKey(key)) updates.Add([.. row.Skip(keys.Length), .. row.Take(keys.Length)]);
                else inserts.Add(row);
            }

            await BulkInsertAsync(session, transaction, target, [.. keys, .. values], inserts, null, cancellationToken);
            if (values.Length > 0) await BulkUpdateAsync(session, transaction, target, keys, values, updates, cancellationToken);
            if (count) counts[$"{schema}.{table}"] = seen.Count;
            return returnMap && inserts.Count > 0 ? await MapAsync(target, idColumn, keys) : existing;
        }

        /// <summary>Deletes the rows the knowledge base owns (all rows when <paramref name="scope"/> is null) and inserts <paramref name="rows"/>.</summary>
        public async Task ReplaceAsync(string schema, string table, string? scope, string[] columns, IEnumerable<object?[]> rows)
        {
            var target = session.Table(schema, table);
            await ExecuteAsync(session, transaction, $"DELETE FROM {target}{(scope is null ? string.Empty : $" WHERE {scope}")};", null, cancellationToken);
            var list = rows.ToList();
            await BulkInsertAsync(session, transaction, target, columns, list, null, cancellationToken);
            counts[$"{schema}.{table}"] = list.Count;
        }

        private async Task<Dictionary<string, int>> MapAsync(string target, string idColumn, string[] keys)
        {
            var map = new Dictionary<string, int>(KeyComparer);
            await using var command = session.Command(transaction, $"SELECT {Quote(idColumn)}, {string.Join(", ", keys.Select(Quote))} FROM {target};");
            await using var reader = await command.ExecuteReaderAsync(cancellationToken);
            while (await reader.ReadAsync(cancellationToken))
            {
                if (Enumerable.Range(1, keys.Length).Any(reader.IsDBNull)) continue;
                map[Key(Enumerable.Range(1, keys.Length).Select(index => reader.GetValue(index)).ToArray())] = Convert.ToInt32(reader.GetValue(0), CultureInfo.InvariantCulture);
            }

            return map;
        }
    }
