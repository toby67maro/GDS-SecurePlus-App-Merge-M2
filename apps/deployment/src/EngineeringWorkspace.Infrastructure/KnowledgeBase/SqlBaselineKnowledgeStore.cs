        await SqlReferenceSeedStore.UpsertVersionAsync(session, transaction, Dataset, kb.Version, items.Count == 0 ? CombineHashes(kb.Hash, "pending-catalog") : state.EmbeddedHash,
            counts.Values.Sum(), timeProvider.GetUtcNow(), summary, cancellationToken);
        await transaction.CommitAsync(cancellationToken);
        Report(100, "Baselines, delivery data and the question bank are loaded.");
        return new KnowledgeBaseLoadResult(false, $"baselines {kb.Version}", counts, started.Elapsed);
    }

    /// <summary>CIS Controls v8.1, NIST SP 800-53 R5.2 and NIST CSF 2.0 requirements (loaded by phase 1), keyed by framework and requirement code.</summary>
    private static async Task<Dictionary<string, int>> RequirementsAsync(SqlSession session, DbTransaction transaction, EmbeddedKnowledgeBase kb, CancellationToken cancellationToken)
    {
        var frameworks = kb.Rows("recommendationRequirements").Select(row => Sx(row, 2)!).Distinct(StringComparer.Ordinal).ToArray();
        var map = new Dictionary<string, int>(KeyComparer);
        if (frameworks.Length == 0) return map;
        var rows = await QueryAsync(session, transaction,
            $"SELECT f.Code AS F, r.RequirementCode AS R, r.RequirementId AS Id FROM {session.Table("fw", "Requirement")} AS r " +
            $"JOIN {session.Table("fw", "FrameworkVersion")} AS v ON v.FrameworkVersionId = r.FrameworkVersionId JOIN {session.Table("fw", "Framework")} AS f ON f.FrameworkId = v.FrameworkId " +
            $"WHERE f.Code IN ({string.Join(", ", frameworks.Select((_, index) => $"@f{index}"))});",
            Parameters(frameworks.Select((code, index) => ($"@f{index}", (object?)code)).ToArray()), cancellationToken);
        foreach (var row in rows) map[Key(row["F"], row["R"])] = Convert.ToInt32(row["Id"], CultureInfo.InvariantCulture);
        return map;
    }

    private static async Task<Dictionary<string, int>> CodeMapAsync(SqlSession session, DbTransaction transaction, string schema, string table, string idColumn, string codeColumn,
        CancellationToken cancellationToken)
    {
        var map = new Dictionary<string, int>(KeyComparer);
        foreach (var row in await QueryAsync(session, transaction, $"SELECT {idColumn} AS Id, {codeColumn} AS Code FROM {session.Table(schema, table)};", null, cancellationToken))
            if (row["Code"] is string code) map[code] = Convert.ToInt32(row["Id"], CultureInfo.InvariantCulture);
        return map;
    }

    /// <summary>GDS standard items (written by the catalog seed) keyed by their phase-group reference, e.g. P0-T1-PKO-001.</summary>
    private static async Task<Dictionary<string, List<int>>> StandardItemsAsync(SqlSession session, DbTransaction transaction, CancellationToken cancellationToken)
    {
        var map = new Dictionary<string, List<int>>(KeyComparer);
        foreach (var row in await QueryAsync(session, transaction,
                     $"SELECT StandardItemId AS Id, PhaseGroupRef AS Ref FROM {session.Table("gds", "StandardItem")} WHERE PhaseGroupRef IS NOT NULL ORDER BY StandardItemId;", null,
                     cancellationToken))
        {
            var reference = (string)row["Ref"]!;
            if (!map.TryGetValue(reference, out var list)) map[reference] = list = [];
            list.Add(Convert.ToInt32(row["Id"], CultureInfo.InvariantCulture));
        }

        return map;
    }

    private static DateTime? Date(string? text) =>
        DateTime.TryParseExact(text, ["yyyy-MM-dd", "yyyy-MM-ddTHH:mm:ss", "yyyy-MM-dd HH:mm:ss"], CultureInfo.InvariantCulture, DateTimeStyles.None, out var value) ? value : null;

    private Task<SqlSession> OpenAsync(CancellationToken cancellationToken) =>
        SqlSession.OpenAsync(database, connections, message => new InvalidOperationException(message), cancellationToken);
