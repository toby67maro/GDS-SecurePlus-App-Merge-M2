        int Baseline(string code) => baselines[code];
        await BulkUpdateAsync(session, transaction, session.Table("cfg", "Baseline"), ["BaselineId"], ["SupersededByBaselineId"],
            baselineRows.Where(row => Sx(row, 10) is { } next && baselines.ContainsKey(next)).Select(row => new object?[] { baselines[Sx(row, 10)!], baselines[Sx(row, 0)!] }).ToList(),
            cancellationToken);
        var profiles = await loader.UpsertAsync("cfg", "BaselineProfile", "BaselineProfileId", ["BaselineId", "Code"], ["Name", "ProfileLevel", "QualifierCode", "IsAddOn", "Description"],
            kb.Rows("profiles").Select(row => new object?[] { Baseline(Sx(row, 0)!), Sx(row, 1), Sx(row, 2), Ix(row, 3), Sx(row, 4), Bit(row, 5), Sx(row, 6) }));
        var sectionRows = kb.Rows("sections").ToArray();
        var sections = await loader.UpsertAsync("cfg", "BaselineSection", "BaselineSectionId", ["BaselineId", "SectionNumber"], ["Title", "Description", "SortKey"],
            sectionRows.Select(row => new object?[] { Baseline(Sx(row, 0)!), Sx(row, 1), Sx(row, 3), Sx(row, 4), Sx(row, 5) }));
        int? Section(string baseline, string? number) => number is not null && sections.TryGetValue(Key(Baseline(baseline), number), out var id) ? id : null;
        await BulkUpdateAsync(session, transaction, session.Table("cfg", "BaselineSection"), ["BaselineSectionId"], ["ParentSectionId"],
            sectionRows.Where(row => Section(Sx(row, 0)!, Sx(row, 2)) is not null)
                .Select(row => new object?[] { Section(Sx(row, 0)!, Sx(row, 2)), Section(Sx(row, 0)!, Sx(row, 1)) }).ToList(), cancellationToken);
        await loader.UpsertAsync("cfg", "GpoPackage", "GpoPackageId", ["BaselineId", "BackupId"], ["GpoGuid", "DisplayName", "ScopeCode", "GpReportFile"],
            kb.Rows("gpoPackages").Select(row => new object?[] { Baseline(Sx(row, 0)!), Sx(row, 1), Sx(row, 2), Sx(row, 3), Sx(row, 4), Sx(row, 5) }), returnMap: false);

        // ----- Recommendations and their verbatim text -----
        Report(12, $"Writing {kb.Count("recommendations"):N0} baseline recommendations...");
        var recommendations = await loader.UpsertAsync("cfg", "Recommendation", "RecommendationId", ["BaselineId", "RecNumber"],
            ["BaselineSectionId", "Title", "AssessmentTypeCode", "CategoryText", "LevelText", "Summary", "RationaleSummary", "ImpactSummary", "DefaultValue", "RecommendedValue",
             "GridId", "ExternalId", "MinimumOsVersion", "HowToVerifyCode", "IsDeprecated", "SourceDocumentId", "PageNumber", "SourceRowRef"],
            kb.Rows("recommendations").Select(row => new object?[]
            {
                Baseline(Sx(row, 0)!), Sx(row, 1), Section(Sx(row, 0)!, Sx(row, 2)), Sx(row, 4), Sx(row, 5), Sx(row, 6), Sx(row, 7), Sx(row, 8), Sx(row, 9), Sx(row, 10), Sx(row, 11),
                Sx(row, 12), Sx(row, 13), Sx(row, 14), Sx(row, 15), Sx(row, 16), Bit(row, 17), Source(Sx(row, 18)), Ix(row, 19), Sx(row, 20)
            }));
        int? Recommendation(JsonElement row) => recommendations.TryGetValue(Key(Baseline(Sx(row, 0)!), Sx(row, 1)), out var id) ? id : null;
        Report(30, $"Writing the text of {kb.Count("sourceTexts"):N0} CIS recommendations (internal use only)...");
        await loader.ReplaceAsync("cfg", "RecommendationSourceText", null,
            ["RecommendationId", "DescriptionText", "RationaleText", "ImpactText", "AuditText", "RemediationText", "AdditionalInfoText", "WarningText", "ReferencesText", "LicenseId",
             "IsInternalOnly"],
            kb.Rows("sourceTexts").Where(row => Recommendation(row) is not null).Select(row => new object?[]
            {
                Recommendation(row), Sx(row, 2), Sx(row, 3), Sx(row, 4), Sx(row, 5), Sx(row, 6), Sx(row, 7), Sx(row, 8), Sx(row, 9), License(Sx(row, 10)), Bit(row, 11)
            }));
        Report(55, "Writing profiles and framework links...");
        await loader.ReplaceAsync("cfg", "RecommendationProfile", null, ["RecommendationId", "BaselineProfileId", "RecommendedValue"],
            kb.Rows("recommendationProfiles").Where(row => Recommendation(row) is not null && profiles.ContainsKey(Key(Baseline(Sx(row, 0)!), Sx(row, 2))))
                .Select(row => new object?[] { Recommendation(row), profiles[Key(Baseline(Sx(row, 0)!), Sx(row, 2))], Sx(row, 3) }));
        var requirements = await RequirementsAsync(session, transaction, kb, cancellationToken);
        var cisSource = mappingSources["CIS-BENCHMARK"];
        await loader.ReplaceAsync("cfg", "RecommendationRequirement", $"MappingSourceId = {cisSource}",
            ["RecommendationId", "RequirementId", "MappingSourceId", "RelationshipTypeId", "ControlsVersionLabel", "IsExplicitlyNotMapped"],
            kb.Rows("recommendationRequirements").Where(row => Recommendation(row) is not null && requirements.ContainsKey(Key(Sx(row, 2), Sx(row, 3))))
                .Select(row => new object?[]
                {
                    Recommendation(row), requirements[Key(Sx(row, 2), Sx(row, 3))], mappingSources[Sx(row, 4)!], relationships[Sx(row, 5)!], Sx(row, 6), session.Bool(false)
                }));

        // ----- Technical settings -----
        Report(62, $"Writing {kb.Count("settings"):N0} technical settings...");
        var settings = await loader.UpsertAsync("cfg", "Setting", "SettingId", ["SettingKey"],
            ["SettingTypeCode", "PlatformId", "Name", "FriendlyName", "CategoryPath", "ScopeCode", "IntuneSettingDefinitionId", "OmaUri", "GpoPath", "RegistryHive", "RegistryKey",
             "RegistryValueName", "RegistryValueType", "PowerShellCmdlet", "MinOsVersion", "IsAdmxBacked", "IsDeprecated", "SourceDocumentId"],
            kb.Rows("settings").Select(row => new object?[]
            {
                Sx(row, 0), Sx(row, 1), Platform(Sx(row, 2)), Sx(row, 3), Sx(row, 4), Sx(row, 5), Sx(row, 6), Sx(row, 7), Sx(row, 8), Sx(row, 9), Sx(row, 10), Sx(row, 11), Sx(row, 12),
