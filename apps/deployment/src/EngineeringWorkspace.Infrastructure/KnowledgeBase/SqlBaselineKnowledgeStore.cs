        var relationships = await loader.UpsertAsync("ref", "RelationshipType", "RelationshipTypeId", ["Code"], ["Name", "CountsAsSatisfies", "Description"],
            EaasReferenceData.RelationshipTypes.Select(type => new object?[] { type.Code, type.Name, session.Bool(type.CountsAsSatisfies), type.Description }), count: false);

        // ----- Platforms, baseline sources, baselines, profiles, sections, GPO packages -----
        Report(6, "Writing platforms and baselines...");
        var platformRows = kb.Rows("platforms").ToArray();
        var platforms = await loader.UpsertAsync("cfg", "Platform", "PlatformId", ["Code"], ["Name", "PlatformFamilyCode", "Vendor", "VersionLabel", "IsActive"],
            platformRows.Select(row => new object?[] { Sx(row, 0), Sx(row, 1), Sx(row, 2), Sx(row, 3), Sx(row, 4), session.Bool(true) }));
        int? Platform(string? code) => code is not null && platforms.TryGetValue(code, out var id) ? id : null;
        await BulkUpdateAsync(session, transaction, session.Table("cfg", "Platform"), ["PlatformId"], ["ParentPlatformId"],
            platformRows.Where(row => Platform(Sx(row, 5)) is not null).Select(row => new object?[] { Platform(Sx(row, 5)), platforms[Sx(row, 0)!] }).ToList(), cancellationToken);
        var baselineSources = await loader.UpsertAsync("cfg", "BaselineSource", "BaselineSourceId", ["Code"], ["Name", "Publisher", "IsGdsInternal", "LicenseId", "Url"],
            kb.Rows("baselineSources").Select(row => new object?[] { Sx(row, 0), Sx(row, 1), Sx(row, 2), Bit(row, 3), License(Sx(row, 4)), Sx(row, 5) }));
        var baselineRows = kb.Rows("baselines").ToArray();
        var baselines = await loader.UpsertAsync("cfg", "Baseline", "BaselineId", ["Code"],
            ["BaselineSourceId", "PlatformId", "Name", "Version", "ReleaseDate", "DeliveryMechanismCode", "TargetCloudCode", "IsCurrent", "IsArchived", "SourceDocumentId",
             "RecommendationCount", "Notes"],
            baselineRows.Select(row => new object?[]
            {
                Sx(row, 0), baselineSources[Sx(row, 1)!], Platform(Sx(row, 2)), Sx(row, 3), Sx(row, 4), Date(Sx(row, 5)), Sx(row, 6), Sx(row, 7), Bit(row, 8), Bit(row, 9),
                Source(Sx(row, 11)), Ix(row, 12), Sx(row, 13)
