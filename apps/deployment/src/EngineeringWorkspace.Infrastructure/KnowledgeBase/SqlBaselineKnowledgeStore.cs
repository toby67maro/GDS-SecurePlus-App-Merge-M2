        await loader.UpsertAsync("eux", "AnswerOption", "AnswerOptionId", ["QuestionId", "Sequence"], ["OptionText", "OptionValue", "IsDefault"],
            kb.Rows("answerOptions").Where(row => questions.ContainsKey(Sx(row, 0)!))
                .Select(row => new object?[] { questions[Sx(row, 0)!], Ix(row, 1), Sx(row, 2), Sx(row, 3), Bit(row, 4) }), returnMap: false);
        await loader.ReplaceAsync("eux", "QuestionRule", null, ["QuestionModuleId", "ConditionExpression", "Priority", "Notes"],
            kb.Rows("questionRules").Select(row => new object?[] { null, Sx(row, 1), Ix(row, 2), Sx(row, 3) }));
