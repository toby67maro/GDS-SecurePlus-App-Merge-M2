/// <summary>
/// Knowledge base phase 2 (dataset "knowledge-base-phase-2", generated by build/scripts/knowledge/generate_baselines.py):
/// the CIS Benchmarks and Microsoft security baselines (cfg.*), their links to CIS Controls v8, NIST SP 800-53 and CSF 2.0
/// and to MITRE ATT&amp;CK, the GDS work breakdown structure (dlv.*), the question bank (eux.*), the deployment method matrix
/// (deploy.*, kb.Product) and the source documents and licences (src.*). Reference rows are upserted by natural key and
/// keep their IDs; link rows are replaced. It runs after phase 1 (requirements, techniques) and links WBS tasks and
/// discovery questions to the catalog's GDS standard items, so the loaded state includes the catalog's content hash.
/// </summary>
public sealed class SqlBaselineKnowledgeStore(IDatabaseStatusService database, DatabaseConnectionFactory connections, TimeProvider timeProvider) : IKnowledgeBaseStore
{
    public const string Dataset = "knowledge-base-phase-2";
    private const string CatalogDataset = "catalog";

    public bool IsAvailable => database.Settings.Provider != DatabaseProvider.None && database.LatestStatus?.State == DatabaseOverallState.Ready;

    public async Task<KnowledgeBaseState> GetStateAsync(CancellationToken cancellationToken = default)
    {
        var embedded = EmbeddedKnowledgeBase.Baselines;
        await using var session = await OpenAsync(cancellationToken);
        var rows = await QueryAsync(session, null, $"SELECT Dataset, Version, ContentHash, AppliedAtUtc, Summary FROM {session.Table("secureplus", "SeedVersion")} " +
                                                   "WHERE Dataset IN (@dataset, @catalog);", Parameters(("@dataset", Dataset), ("@catalog", CatalogDataset)), cancellationToken);
        var row = rows.FirstOrDefault(candidate => Dataset.Equals(candidate["Dataset"] as string, StringComparison.Ordinal));
        var catalog = rows.FirstOrDefault(candidate => CatalogDataset.Equals(candidate["Dataset"] as string, StringComparison.Ordinal))?["ContentHash"] as string;
        return new KnowledgeBaseState($"baselines {embedded.Version}", ExpectedHash(embedded, catalog), row?["Version"] as string, row?["ContentHash"] as string,
            row?["AppliedAtUtc"] is { } at ? SqlSession.ReadDate(at) : null, row?["Summary"] as string);
    }

    /// <summary>The links to GDS standard items depend on the catalog, so a new catalog makes this dataset stale.</summary>
    private static string ExpectedHash(EmbeddedKnowledgeBase embedded, string? catalogHash) => CombineHashes(embedded.Hash, catalogHash ?? "no-catalog");

    public async Task<KnowledgeBaseLoadResult> LoadAsync(bool force, IProgress<(double Progress, string Activity)>? progress, CancellationToken cancellationToken = default)
    {
