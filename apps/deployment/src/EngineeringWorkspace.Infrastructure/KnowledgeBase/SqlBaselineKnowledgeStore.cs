        await loader.ReplaceAsync("cfg", "SettingAlias", null, ["SettingId", "AliasTypeCode", "AliasValue", "SourceDocumentId"],
            kb.Rows("settingAliases").Where(row => settings.ContainsKey(Sx(row, 0)!))
                .Select(row => new object?[] { settings[Sx(row, 0)!], Sx(row, 1), Sx(row, 2), Source(Sx(row, 3)) }));
        await loader.ReplaceAsync("cfg", "RecommendationSetting", null, ["RecommendationId", "SettingId", "ExpectedValue", "OperatorCode", "ValueUnit", "IsPrimary"],
            kb.Rows("recommendationSettings").Where(row => Recommendation(row) is not null && settings.ContainsKey(Sx(row, 2)!))
                .Select(row => new object?[] { Recommendation(row), settings[Sx(row, 2)!], Sx(row, 3), Sx(row, 4), Sx(row, 5), Bit(row, 6) }));
        await loader.ReplaceAsync("cfg", "StigReference", null,
            ["RecommendationId", "StigId", "VulId", "RuleId", "SeverityCat", "StigTitle", "StigVersion", "StigRelease", "BenchmarkDate"],
            kb.Rows("stigReferences").Where(row => Recommendation(row) is not null).Select(row => new object?[]
                { Recommendation(row), Sx(row, 2), Sx(row, 3), Sx(row, 4), Ix(row, 5), Sx(row, 6), Sx(row, 7), Sx(row, 8), Date(Sx(row, 9)) }));
        var techniques = await CodeMapAsync(session, transaction, "threat", "AttackTechnique", "TechniqueId", "TechniqueCode", cancellationToken);
        var mitigations = await CodeMapAsync(session, transaction, "threat", "AttackMitigation", "MitigationId", "MitigationCode", cancellationToken);
        var attackSource = mappingSources["CIS-BENCHMARK-ATTACK"];
        await loader.ReplaceAsync("threat", "RecommendationTechnique", $"MappingSourceId = {attackSource}", ["RecommendationId", "TechniqueId", "MappingSourceId", "MitigationId"],
            kb.Rows("recommendationTechniques").Where(row => Recommendation(row) is not null && techniques.ContainsKey(Sx(row, 2)!)).Select(row => new object?[]
                { Recommendation(row), techniques[Sx(row, 2)!], attackSource, Sx(row, 3) is { } mitigation && mitigations.TryGetValue(mitigation, out var id) ? id : null }));

        // ----- GDS delivery: phases, workstreams, WBS -----
        Report(78, "Writing the work breakdown structure...");
        var phases = await loader.UpsertAsync("dlv", "Phase", "PhaseId", ["PhaseSetCode", "Code"], ["Name", "SortOrder", "Description"],
            kb.Rows("phases").Select(row => new object?[] { Sx(row, 0), Sx(row, 1), Sx(row, 2), Ix(row, 3), Sx(row, 4) }));
        int? Phase(string? set, string? code) => code is not null && phases.TryGetValue(Key(set, code), out var id) ? id : null;
        var workstreams = await loader.UpsertAsync("dlv", "Workstream", "WorkstreamId", ["Code"], ["Name", "Description"],
            kb.Rows("workstreams").Select(row => new object?[] { Sx(row, 0), Sx(row, 1), Sx(row, 2) }));
        var standards = await CodeMapAsync(session, transaction, "gds", "Standard", "StandardId", "Code", cancellationToken);
        var templates = await loader.UpsertAsync("dlv", "WbsTemplate", "WbsTemplateId", ["Code"], ["Name", "Version", "StandardId", "SourceDocumentId", "Notes"],
            kb.Rows("wbsTemplates").Select(row => new object?[]
                { Sx(row, 0), Sx(row, 1), Sx(row, 2), Sx(row, 3) is { } standard && standards.TryGetValue(standard, out var id) ? id : null, Source(Sx(row, 4)), Sx(row, 5) }));
