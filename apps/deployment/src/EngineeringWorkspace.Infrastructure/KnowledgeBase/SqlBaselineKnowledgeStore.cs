        int? Task(string? template, string? code) =>
            template is not null && templates.TryGetValue(template, out var templateId) && tasks.TryGetValue(Key(templateId, code), out var id) ? id : null;
        await loader.ReplaceAsync("dlv", "WbsTaskDependency", null, ["WbsTaskId", "PredecessorWbsTaskId", "DependencyTypeCode", "LagDays"],
            kb.Rows("wbsDependencies").Where(row => Task(Sx(row, 0), Sx(row, 1)) is not null && Task(Sx(row, 0), Sx(row, 2)) is not null)
                .Select(row => new object?[] { Task(Sx(row, 0), Sx(row, 1)), Task(Sx(row, 0), Sx(row, 2)), "FS", 0m }));
        var items = await StandardItemsAsync(session, transaction, cancellationToken);
        await loader.ReplaceAsync("dlv", "WbsTaskCoverage", null, ["WbsTaskId", "StandardItemId"],
            kb.Rows("wbsCoverage").Where(row => Task(Sx(row, 0), Sx(row, 1)) is not null && items.ContainsKey(Sx(row, 2)!))
