                Bit(row, 11), Bit(row, 12), Sx(row, 14)
            }));
        int? Source(string? code) => code is not null && sources.TryGetValue(code, out var id) ? id : null;
        await BulkUpdateAsync(session, transaction, session.Table("src", "SourceDocument"), ["SourceDocumentId"], ["SupersededByDocumentId"],
            sourceRows.Where(row => Source(Sx(row, 13)) is not null).Select(row => new object?[] { Source(Sx(row, 13)), sources[Sx(row, 0)!] }).ToList(), cancellationToken);
        var mappingSources = await loader.UpsertAsync("ref", "MappingSource", "MappingSourceId", ["Code"], ["Name", "Publisher", "AuthorityLevelCode", "DefaultConfidence", "Url"],
