        await loader.UpsertAsync("deploy", "ServiceMethodCoverage", "ServiceMethodCoverageId", ["SettingGroup"],
            ["ProductId", "DeploymentMethodId", "JsonNativeCode", "AppOnlyUnattended", "ReadWriteCode", "PortalOnlyGaps", "DriftOption", "RepoStatusCode", "SourceUrl", "ConfidenceCode"],
