/// <summary>
/// Knowledge base phase 3 (dataset "knowledge-base-phase-3", generated by build/scripts/knowledge/generate_phase3.py):
/// Microsoft licensing (SKUs, service plans as capabilities), MITRE CTID threat coverage, service tiers, the Customer
/// Deployment Checklist standard, configuration changes, known issues and guidance from the catalog, Microsoft baseline
/// changes, cross-baseline relations and procedures, experience expectations, deployment rings, framework properties,
/// scope categories, status labels, the scoring model with enrichment values and item scores, and the load log.
/// Runs after phases 1 and 2 and the catalog; reference rows are upserted (stable IDs), links replaced.
/// </summary>
public sealed class SqlPhase3KnowledgeStore(IDatabaseStatusService database, DatabaseConnectionFactory connections, TimeProvider timeProvider) : IKnowledgeBaseStore
{
    public const string Dataset = "knowledge-base-phase-3";

    public bool IsAvailable => database.Settings.Provider != DatabaseProvider.None && database.LatestStatus?.State == DatabaseOverallState.Ready;

    public async Task<KnowledgeBaseState> GetStateAsync(CancellationToken cancellationToken = default)
    {
        var embedded = EmbeddedKnowledgeBase.Phase3;
        await using var session = await OpenAsync(cancellationToken);
        var rows = await QueryAsync(session, null, $"SELECT Dataset, Version, ContentHash, AppliedAtUtc, Summary FROM {session.Table("secureplus", "SeedVersion")} " +
                                                   "WHERE Dataset IN (@dataset, @catalog);", Parameters(("@dataset", Dataset), ("@catalog", "catalog")), cancellationToken);
        var row = rows.FirstOrDefault(candidate => Dataset.Equals(candidate["Dataset"] as string, StringComparison.Ordinal));
        var catalog = rows.FirstOrDefault(candidate => "catalog".Equals(candidate["Dataset"] as string, StringComparison.Ordinal))?["ContentHash"] as string;
        return new KnowledgeBaseState($"phase 3 {embedded.Version}", CombineHashes(embedded.Hash, catalog ?? "no-catalog"), row?["Version"] as string,
            row?["ContentHash"] as string, row?["AppliedAtUtc"] is { } at ? SqlSession.ReadDate(at) : null, row?["Summary"] as string);
    }

    public async Task<KnowledgeBaseLoadResult> LoadAsync(bool force, IProgress<(double Progress, string Activity)>? progress, CancellationToken cancellationToken = default)
    {
        var kb = EmbeddedKnowledgeBase.Phase3;
        var started = Stopwatch.StartNew();
        var startedAt = timeProvider.GetUtcNow();
        var state = await GetStateAsync(cancellationToken);
        if (!force && state.IsCurrent) return new KnowledgeBaseLoadResult(true, $"phase 3 {kb.Version}", new Dictionary<string, int>(), started.Elapsed);

        await using var session = await OpenAsync(cancellationToken);
        session.CommandTimeoutSeconds = Math.Max(session.CommandTimeoutSeconds, 600);
        await using var transaction = await session.Connection.BeginTransactionAsync(IsolationLevel.ReadCommitted, cancellationToken);
        var counts = new Dictionary<string, int>(StringComparer.Ordinal);
        var loader = new Loader(session, transaction, counts, cancellationToken);
        void Report(double percent, string activity) => progress?.Report((percent, activity));
        object Bit(JsonElement row, int index) => session.Bool(row[index].ValueKind == JsonValueKind.Number ? row[index].GetInt32() != 0 : row[index].ValueKind == JsonValueKind.True);
        object? NullableBit(JsonElement row, int index) => row[index].ValueKind is JsonValueKind.Null ? null : Bit(row, index);
        int? Lookup(Dictionary<string, int> map, string? code) => code is not null && map.TryGetValue(code, out var id) ? id : null;
        var today = timeProvider.GetUtcNow().UtcDateTime.Date;

        // ----- Reference values -----
        Report(2, "Writing licences, sources and rating scales...");
        var licenses = await loader.UpsertAsync("src", "License", "LicenseId", ["Code"],
            ["Name", "Url", "AllowsCommercialUse", "AllowsRedistribution", "AllowsDerivatives", "AllowsCustomerFacingText", "AttributionText", "Notes"],
            kb.Rows("licenses").Select(row => new object?[] { Sx(row, 0), Sx(row, 1), Sx(row, 2), Bit(row, 3), Bit(row, 4), Bit(row, 5), Bit(row, 6), Sx(row, 7), Sx(row, 8) }));
        var sources = await loader.UpsertAsync("src", "SourceDocument", "SourceDocumentId", ["Code"],
            ["Title", "Publisher", "DocumentTypeCode", "Version", "PublishedDate", "Location", "FileName", "FileHashSha256", "LicenseId", "IsAuthoritative", "IsGdsInternal",
             "IsCurrent", "Notes"],
            kb.Rows("sources").Select(row => new object?[]
            {
                Sx(row, 0), Sx(row, 1), Sx(row, 2), Sx(row, 3), Sx(row, 4), Date(Sx(row, 5)), Sx(row, 6), Sx(row, 7), Sx(row, 8), Lookup(licenses, Sx(row, 9)), Bit(row, 10),
                Bit(row, 11), Bit(row, 12), Sx(row, 14)
            }));
        await loader.UpsertAsync("src", "SourceObject", "SourceObjectId", ["SourceDocumentId", "ObjectName"], ["TargetTables", "RowCount", "Notes"],
            kb.Rows("sourceObjects").Where(row => sources.ContainsKey(Sx(row, 0)!))
                .Select(row => new object?[] { sources[Sx(row, 0)!], Sx(row, 1), Sx(row, 3), Ix(row, 4), Sx(row, 5) }), returnMap: false);
        var mappingSources = await loader.UpsertAsync("ref", "MappingSource", "MappingSourceId", ["Code"], ["Name", "Publisher", "AuthorityLevelCode", "DefaultConfidence", "Url"],
            kb.Rows("mappingSources").Select(row => new object?[] { Sx(row, 0), Sx(row, 1), Sx(row, 2), Sx(row, 3), Ix(row, 4), Sx(row, 5) }));
        mappingSources = await CodeMapAsync(session, transaction, "ref", "MappingSource", "MappingSourceId", "Code", cancellationToken);
        var relationships = await CodeMapAsync(session, transaction, "ref", "RelationshipType", "RelationshipTypeId", "Code", cancellationToken);
        var scales = await loader.UpsertAsync("ref", "RatingScale", "RatingScaleId", ["Code"], ["Name", "MinValue", "MaxValue", "HigherIsWorse", "Description"],
            kb.Rows("ratingScales").Select(row => new object?[] { Sx(row, 0), Sx(row, 1), Dx(row, 2), Dx(row, 3), session.Bool(row[4].GetBoolean()), Sx(row, 5) }));
        var scaleValues = await loader.UpsertAsync("ref", "RatingScaleValue", "RatingScaleValueId", ["RatingScaleId", "Label"], ["NumericValue", "BinLow", "BinHigh", "ColorHex"],
            kb.Rows("ratingScales").SelectMany(scale => scale[6].EnumerateArray().Select(value => new object?[]
                { scales[Sx(scale, 0)!], Sx(value, 1), Dx(value, 0), Dx(value, 2), Dx(value, 3), Sx(value, 4) })));
        int? ScaleValue(string scale, string? label) => label is not null && scaleValues.TryGetValue(Key(scales[scale], label), out var id) ? id : null;
        int? AnyScaleValue(string? label) => ScaleValue("GDS-LOW-MEDIUM-HIGH", label) ?? ScaleValue("NIST-800-30", label);
        var entityTypes = await CodeMapAsync(session, transaction, "ref", "EntityType", "EntityTypeId", "Code", cancellationToken);
        var frameworks = await CodeMapAsync(session, transaction, "fw", "Framework", "FrameworkId", "Code", cancellationToken);
        var baselineSources = await loader.UpsertAsync("cfg", "BaselineSource", "BaselineSourceId", ["Code"], ["Name", "Publisher", "IsGdsInternal", "LicenseId"],
            [["GDS", "GDS standards and checklists", "Global Data Systems", session.Bool(true), Lookup(licenses, "GDS-INTERNAL")]], count: false);
        baselineSources = await CodeMapAsync(session, transaction, "cfg", "BaselineSource", "BaselineSourceId", "Code", cancellationToken);

        // ----- Products, licensing, capabilities -----
        Report(8, $"Writing {kb.Count("licenseSkus"):N0} licences and {kb.Count("capabilities"):N0} capabilities...");
        await loader.UpsertAsync("kb", "Product", "ProductId", ["Code"], ["Name", "Vendor", "ProductFamilyCode", "AdminCenterName", "AdminPortalUrl"],
            kb.Rows("products").Select(row => new object?[] { Sx(row, 0), Sx(row, 1), Sx(row, 2), Sx(row, 3), Sx(row, 4), Sx(row, 5) }), returnMap: false);
        var products = await CodeMapAsync(session, transaction, "kb", "Product", "ProductId", "Code", cancellationToken);
        var skus = await loader.UpsertAsync("kb", "LicenseSku", "LicenseSkuId", ["SkuPartNumber"], ["Name", "Vendor", "LicenseFamilyCode", "CloudEnvironmentCode", "IsAddOn", "Notes"],
            kb.Rows("licenseSkus").Select(row => new object?[] { Sx(row, 0), Sx(row, 1), Sx(row, 2), Sx(row, 3), Sx(row, 4), Bit(row, 5), Sx(row, 6) }));
        var capabilities = await loader.UpsertAsync("kb", "Capability", "CapabilityId", ["Code"], ["ProductId", "Name", "CategoryText", "Description", "DocUrl", "PortalPath"],
            kb.Rows("capabilities").Select(row => new object?[] { Sx(row, 0), Lookup(products, Sx(row, 1)), Sx(row, 2), Sx(row, 3), Sx(row, 4), Sx(row, 5), Sx(row, 6) }));
        await loader.ReplaceAsync("kb", "SkuCapability", null, ["LicenseSkuId", "CapabilityId", "ServicePlanName"],
            kb.Rows("skuCapabilities").Where(row => skus.ContainsKey(Sx(row, 0)!) && capabilities.ContainsKey(Sx(row, 1)!))
                .Select(row => new object?[] { skus[Sx(row, 0)!], capabilities[Sx(row, 1)!], Sx(row, 2) }));

        // ----- Threat coverage (MITRE CTID) -----
        Report(18, "Writing MITRE CTID threat coverage...");
        var extra = kb.Rows("extraTechniques").ToArray();
        await loader.UpsertAsync("threat", "AttackTechnique", "TechniqueId", ["TechniqueCode"], ["Name", "IsSubTechnique", "AttackVersion", "IsDeprecated", "Url"],
            extra.Select(row => new object?[] { Sx(row, 0), Sx(row, 2), Bit(row, 3), Sx(row, 4), session.Bool(false), Sx(row, 5) }), returnMap: false);
        var techniques = await CodeMapAsync(session, transaction, "threat", "AttackTechnique", "TechniqueId", "TechniqueCode", cancellationToken);
        await BulkUpdateAsync(session, transaction, session.Table("threat", "AttackTechnique"), ["TechniqueId"], ["ParentTechniqueId"],
            extra.Where(row => Lookup(techniques, Sx(row, 1)) is not null).Select(row => new object?[] { techniques[Sx(row, 1)!], techniques[Sx(row, 0)!] }).ToList(), cancellationToken);
        var ctidCapabilitySources = new[] { "CTID-M365", "CTID-AZURE" }.Select(code => mappingSources[code]).ToArray();
        await loader.ReplaceAsync("threat", "CapabilityTechnique", $"MappingSourceId IN ({string.Join(", ", ctidCapabilitySources)})",
            ["CapabilityId", "TechniqueId", "MappingSourceId", "MappingCategoryCode", "MappingValueCode"],
            kb.Rows("capabilityTechniques").Where(row => capabilities.ContainsKey(Sx(row, 0)!) && techniques.ContainsKey(Sx(row, 1)!))
                .Select(row => new object?[] { capabilities[Sx(row, 0)!], techniques[Sx(row, 1)!], mappingSources[Sx(row, 2)!], Sx(row, 3), Sx(row, 4) }));
        var requirements = await RequirementsAsync(session, transaction, cancellationToken);
        int? Requirement(string? framework, string? code) => framework is not null && code is not null && requirements.TryGetValue(Key(framework, code), out var id) ? id : null;
        var ctidRequirementSources = new[] { "CTID-NIST-800-53", "CTID-CIS-CONTROLS" }.Select(code => mappingSources[code]).ToArray();
        await loader.ReplaceAsync("threat", "RequirementTechnique", $"MappingSourceId IN ({string.Join(", ", ctidRequirementSources)})",
            ["RequirementId", "TechniqueId", "MappingSourceId", "MappingCategoryCode", "AttackVersion"],
            kb.Rows("requirementTechniques").Where(row => Requirement(Sx(row, 0), Sx(row, 1)) is not null && techniques.ContainsKey(Sx(row, 2)!))
                .Select(row => new object?[] { Requirement(Sx(row, 0), Sx(row, 1)), techniques[Sx(row, 2)!], mappingSources[Sx(row, 3)!], Sx(row, 4), Sx(row, 5) }));

        // ----- Service tiers -----
        Report(26, "Writing service tiers...");
        var tiers = await CodeMapAsync(session, transaction, "svc", "ServiceTier", "ServiceTierId", "Code", cancellationToken);
        var baseSkus = kb.Rows("tierBaseSkus").ToDictionary(row => Sx(row, 0)!, row => Sx(row, 1)!, StringComparer.OrdinalIgnoreCase);
        await BulkUpdateAsync(session, transaction, session.Table("svc", "ServiceTier"), ["ServiceTierId"], ["Tagline", "BaseLicenseSkuId"],
            kb.Rows("serviceTiers").Where(row => tiers.ContainsKey(Sx(row, 0)!))
                .Select(row => new object?[] { Sx(row, 1), baseSkus.TryGetValue(Sx(row, 0)!, out var sku) ? Lookup(skus, sku) : null, tiers[Sx(row, 0)!] }).ToList(),
            cancellationToken);
        await loader.ReplaceAsync("svc", "TierFeature", null, ["ServiceTierId", "FeatureText", "SortOrder"],
            kb.Rows("tierFeatures").Where(row => tiers.ContainsKey(Sx(row, 0)!)).Select(row => new object?[] { tiers[Sx(row, 0)!], Sx(row, 2), Ix(row, 1) }));
        await loader.ReplaceAsync("svc", "TierCapability", null, ["ServiceTierId", "CapabilityId", "InclusionCode", "Notes"],
            kb.Rows("tierCapabilities").Where(row => tiers.ContainsKey(Sx(row, 0)!) && capabilities.ContainsKey(Sx(row, 1)!))
                .Select(row => new object?[] { tiers[Sx(row, 0)!], capabilities[Sx(row, 1)!], Sx(row, 2), Sx(row, 3) }));

        // ----- Customer Deployment Checklist v2.0 as a GDS standard -----
        Report(30, "Writing the Customer Deployment Checklist standard...");
        var standards = await loader.UpsertAsync("gds", "Standard", "StandardId", ["Code"], ["Name", "Version", "StatusCode", "OwnerName", "SourceDocumentId", "Notes"],
            [["CDC-2.0", "Customer Deployment Checklist v2.0", "2.0", "Current", "GDS Modern Work", Lookup(sources, "GDS-CUSTOMER-DEPLOYMENT-CHECKLIST"),
              "201 baseline controls (Assessment sheet) and 170 optional controls of the Customer Deployment Checklist v2.0."]], count: false);
        await loader.UpsertAsync("gds", "StandardItem", "StandardItemId", ["StandardId", "ItemCode"],
            ["Sequence", "PhaseGroupRef", "TaskName", "ControlCode", "SettingCategory", "SettingName", "TargetConfiguration", "ConfigurationPath", "ValidationMethod", "IsOptional",
             "EngineeringNotes"],
            kb.Rows("checklistItems").Select(row => new object?[]
            {
                standards["CDC-2.0"], Sx(row, 0), Ix(row, 1), Sx(row, 2), Sx(row, 3), Sx(row, 4), Sx(row, 5), Sx(row, 6), Sx(row, 7), Sx(row, 8), Sx(row, 9), Bit(row, 10),
                Sx(row, 11) is { } notes ? $"{notes} Checklist level: {Sx(row, 12)}." : null
            }), returnMap: false);
        var items = await ItemsAsync(session, transaction, cancellationToken);
        await loader.ReplaceAsync("gds", "StandardItemTier", null, ["StandardItemId", "ServiceTierId", "InclusionCode"],
            kb.Rows("checklistTiers").Where(row => items.ContainsKey(Sx(row, 0)!) && tiers.ContainsKey(Sx(row, 1)!))
                .Select(row => new object?[] { items[Sx(row, 0)!], tiers[Sx(row, 1)!], Sx(row, 2) }));
        await loader.ReplaceAsync("gds", "StandardItemRequirement", null, ["StandardItemId", "RequirementId", "MappingSourceId", "RelationshipTypeId"],
            kb.Rows("itemRequirements").Where(row => items.ContainsKey(Sx(row, 0)!) && Requirement(Sx(row, 1), Sx(row, 2)) is not null)
                .Select(row => new object?[] { items[Sx(row, 0)!], Requirement(Sx(row, 1), Sx(row, 2)), mappingSources[Sx(row, 3)!], relationships[Sx(row, 4)!] }));

        // ----- Configuration changes, known issues, guidance -----
        Report(38, $"Writing {kb.Count("configurationChanges"):N0} configuration changes...");
        var changes = await loader.UpsertAsync("kb", "ConfigurationChange", "ConfigurationChangeId", ["Code"],
            ["Name", "Description", "ProductId", "ChangeTypeCode", "DeploymentMethodCode", "DefaultImplementationModeCode", "MinimumLicenseSkuId", "RequiresUserCommunication",
             "RequiresReboot", "RequiresDowntime", "IsReversible", "OwnerRoleCode", "StatusCode"],
            kb.Rows("configurationChanges").Select(row => new object?[]
            {
                Sx(row, 0), Sx(row, 1), Sx(row, 2), Lookup(products, Sx(row, 3)), Sx(row, 4), Sx(row, 5), Sx(row, 6), Lookup(skus, Sx(row, 7)), Bit(row, 8), NullableBit(row, 9),
                NullableBit(row, 10), Bit(row, 11), Sx(row, 12), Sx(row, 13)
            }));
        await loader.ReplaceAsync("kb", "ConfigurationChangeRequirement", null, ["ConfigurationChangeId", "RequirementId", "MappingSourceId", "RelationshipTypeId", "IsDerived", "DerivationPath"],
            kb.Rows("changeRequirements").Where(row => changes.ContainsKey(Sx(row, 0)!) && Requirement(Sx(row, 1), Sx(row, 2)) is not null)
                .Select(row => new object?[]
                    { changes[Sx(row, 0)!], Requirement(Sx(row, 1), Sx(row, 2)), mappingSources[Sx(row, 3)!], relationships[Sx(row, 4)!], Bit(row, 5), Sx(row, 6) }));
        var platforms = await CodeMapAsync(session, transaction, "cfg", "Platform", "PlatformId", "Code", cancellationToken);
        var issues = await loader.UpsertAsync("kb", "KnownIssue", "KnownIssueId", ["Title"], ["Description", "Symptoms", "Workaround", "SeverityScaleValueId", "PlatformId", "ProductId",
                "SourceDocumentId"],
            kb.Rows("knownIssues").Select(row => new object?[]
            {
                Sx(row, 0), Sx(row, 1), Sx(row, 2), Sx(row, 3), ScaleValue("GDS-LOW-MEDIUM-HIGH", Sx(row, 4)), Lookup(platforms, Sx(row, 5)), Lookup(products, Sx(row, 6)),
                Lookup(sources, Sx(row, 7))
            }));
        await loader.ReplaceAsync("kb", "KnownIssueLink", null, ["KnownIssueId", "ConfigurationChangeId", "Notes"],
            kb.Rows("knownIssueLinks").Where(row => issues.ContainsKey(Sx(row, 0)!) && changes.ContainsKey(Sx(row, 2)!))
                .Select(row => new object?[] { issues[Sx(row, 0)!], changes[Sx(row, 2)!], Sx(row, 3) }));
        Report(48, "Writing implementation guidance...");
        var guidanceColumns = new[]
        {
            "ConfigurationChangeId", "StandardItemId", "BusinessImpactText", "EuxImpactText", "Prerequisites", "ImplementationSteps", "ValidationSteps", "RollbackSteps",
            "SupportImpact", "LicenseNotes", "IsCustomerFacing", "ReviewStatusCode", "AuthoredBy", "Version"
        };
        var guidanceRows = kb.Rows("guidance").Select(row => new object?[]
        {
            Sx(row, 0) == "ConfigurationChange" ? Lookup(changes, Sx(row, 1)) : null, Sx(row, 0) == "StandardItem" ? Lookup(items, Sx(row, 1)) : null, Sx(row, 2), Sx(row, 3), Sx(row, 4),
            Sx(row, 5), Sx(row, 6), Sx(row, 7), Sx(row, 8), Sx(row, 9), session.Bool(false), "Draft", "GDS Secure Plus catalog", 1
        }).Concat(kb.Rows("checklistGuidance").Select(row => new object?[]
        {
            null, Lookup(items, Sx(row, 0)), Sx(row, 1), Sx(row, 2) is { Length: > 0 } impact ? $"{impact} user impact." : null, null, Sx(row, 3), null, Sx(row, 4), null, null,
            session.Bool(false), "Draft", "GDS Customer Deployment Checklist v2.0", 1
        })).Where(row => row[0] is not null || row[1] is not null);
        await loader.ReplaceAsync("kb", "Guidance", null, guidanceColumns, guidanceRows);

        // ----- Baseline changes, relations, procedures -----
        Report(55, "Writing baseline changes, relations and procedures...");
        await loader.UpsertAsync("cfg", "Baseline", "BaselineId", ["Code"], ["BaselineSourceId", "PlatformId", "Name", "Version", "IsCurrent", "IsArchived", "Notes"],
            kb.Rows("previousBaselines").Select(row => new object?[]
                { Sx(row, 0), Lookup(baselineSources, Sx(row, 1)), Lookup(platforms, Sx(row, 2)), Sx(row, 3), Sx(row, 4), session.Bool(false), session.Bool(true),
                  "Previous version, recorded for the version-to-version delta." }), count: false);
        var baselines = await CodeMapAsync(session, transaction, "cfg", "Baseline", "BaselineId", "Code", cancellationToken);
        await BulkUpdateAsync(session, transaction, session.Table("cfg", "Baseline"), ["BaselineId"], ["SupersededByBaselineId"],
            kb.Rows("previousBaselines").Where(row => baselines.ContainsKey(Sx(row, 5)!)).Select(row => new object?[] { baselines[Sx(row, 5)!], baselines[Sx(row, 0)!] }).ToList(),
            cancellationToken);
        var settings = await CodeMapAsync(session, transaction, "cfg", "Setting", "SettingId", "SettingKey", cancellationToken);
        await loader.ReplaceAsync("cfg", "BaselineChange", null,
            ["FromBaselineId", "ToBaselineId", "SettingId", "ChangeTypeCode", "OldValue", "NewValue", "OldRegistryInfo", "NewRegistryInfo", "Notes"],
            kb.Rows("baselineChanges").Select(row => new object?[]
                { Lookup(baselines, Sx(row, 0)), Lookup(baselines, Sx(row, 1)), Lookup(settings, Sx(row, 2)), Sx(row, 3), Sx(row, 4), Sx(row, 5), Sx(row, 6), Sx(row, 7), Sx(row, 8) }));
        var recommendations = await RecommendationsAsync(session, transaction, cancellationToken);
        int? Recommendation(string? baseline, string? number) => baseline is not null && number is not null && recommendations.TryGetValue(Key(baseline, number), out var id) ? id : null;
        var crosswalk = mappingSources["GDS-CROSSWALK"];
        await loader.ReplaceAsync("cfg", "RecommendationRelation", $"MappingSourceId = {crosswalk}",
            ["FromRecommendationId", "ToRecommendationId", "RelationTypeCode", "MappingSourceId", "Notes"],
            kb.Rows("relations").Where(row => Recommendation(Sx(row, 0), Sx(row, 1)) is not null && Recommendation(Sx(row, 2), Sx(row, 3)) is not null)
                .Select(row => new object?[] { Recommendation(Sx(row, 0), Sx(row, 1)), Recommendation(Sx(row, 2), Sx(row, 3)), Sx(row, 4), crosswalk, Sx(row, 5) }));
        await loader.ReplaceAsync("cfg", "RecommendationProcedure", null,
            ["RecommendationId", "ProcedureTypeCode", "MethodCode", "Sequence", "StepText", "ScriptText", "IsReadOnly", "Placeholders"],
            kb.Rows("procedures").Where(row => Recommendation(Sx(row, 0), Sx(row, 1)) is not null).Select(row => new object?[]
                { Recommendation(Sx(row, 0), Sx(row, 1)), Sx(row, 2), Sx(row, 3), Ix(row, 4), Sx(row, 5), Sx(row, 6), Bit(row, 7), Sx(row, 8) }));

        // ----- Experience expectations and deployment rings -----
        Report(68, "Writing experience expectations and deployment rings...");
        var areas = await CodeMapAsync(session, transaction, "eux", "ExperienceArea", "ExperienceAreaId", "Code", cancellationToken);
        var expectations = await loader.UpsertAsync("eux", "Expectation", "ExpectationId", ["Code"], ["ExperienceAreaId", "Statement", "Description", "DefaultImportance"],
            kb.Rows("expectations").Select(row => new object?[] { Sx(row, 0), Lookup(areas, Sx(row, 1)), Sx(row, 2), Sx(row, 3), Ix(row, 4) }));
        var options = await AnswerOptionsAsync(session, transaction, cancellationToken);
        await loader.ReplaceAsync("eux", "AnswerExpectation", null, ["AnswerOptionId", "ExpectationId", "Strength"],
            kb.Rows("answerExpectations").Where(row => options.ContainsKey(Key(Sx(row, 0), Sx(row, 1))) && expectations.ContainsKey(Sx(row, 2)!))
                .Select(row => new object?[] { options[Key(Sx(row, 0), Sx(row, 1))], expectations[Sx(row, 2)!], Ix(row, 3) }));
        await loader.ReplaceAsync("eux", "ExpectationImpact", null, ["ExpectationId", "ConfigurationChangeId", "EffectCode", "Severity", "ConfidenceCode"],
            kb.Rows("expectationImpacts").Where(row => expectations.ContainsKey(Sx(row, 0)!) && changes.ContainsKey(Sx(row, 1)!))
                .Select(row => new object?[] { expectations[Sx(row, 0)!], changes[Sx(row, 1)!], Sx(row, 2), Ix(row, 3), "Medium" }));
        await loader.UpsertAsync("deploy", "Ring", "RingId", ["Code"], ["Name", "SortOrder", "DefaultStateCode"],
            kb.Rows("rings").Select(row => new object?[] { Sx(row, 0), Sx(row, 1), Ix(row, 2), Sx(row, 3) }), returnMap: false);

        // ----- Framework properties, scope categories, status labels -----
        Report(72, "Writing framework properties and scope categories...");
        var properties = await loader.UpsertAsync("ref", "PropertyDefinition", "PropertyDefinitionId", ["Code"], ["Name", "DataTypeCode", "AppliesToEntityTypeId", "FrameworkId", "Description"],
            kb.Rows("propertyDefinitions").Select(row => new object?[]
                { Sx(row, 0), Sx(row, 1), Sx(row, 2), Lookup(entityTypes, Sx(row, 3)), Lookup(frameworks, Sx(row, 4)), Sx(row, 5) }));
        await loader.ReplaceAsync("fw", "RequirementProperty", null, ["RequirementId", "PropertyDefinitionId", "ValueText", "ValueNumber", "ValueBit"],
            kb.Rows("requirementProperties").Where(row => Requirement(Sx(row, 0), Sx(row, 1)) is not null && properties.ContainsKey(Sx(row, 2)!))
                .GroupBy(row => Key(Requirement(Sx(row, 0), Sx(row, 1)), properties[Sx(row, 2)!]), KeyComparer).Select(group => group.First())
                .Select(row => new object?[] { Requirement(Sx(row, 0), Sx(row, 1)), properties[Sx(row, 2)!], Sx(row, 3), Dx(row, 4), NullableBit(row, 5) }));
        await loader.ReplaceAsync("kb", "RequirementCapability", null, ["RequirementId", "CapabilityId", "MappingSourceId", "ToolingText"],
            kb.Rows("requirementCapabilities").Where(row => Requirement(Sx(row, 0), Sx(row, 1)) is not null && capabilities.ContainsKey(Sx(row, 2)!))
                .Select(row => new object?[] { Requirement(Sx(row, 0), Sx(row, 1)), capabilities[Sx(row, 2)!], mappingSources[Sx(row, 3)!], Sx(row, 4) }));
        var versions = await FrameworkVersionsAsync(session, transaction, cancellationToken);
        await loader.UpsertAsync("fw", "ScopeCategory", "ScopeCategoryId", ["FrameworkVersionId", "Code"], ["Name", "SuggestedLabel", "Description"],
            kb.Rows("scopeCategories").Where(row => versions.ContainsKey(Sx(row, 0)!))
                .Select(row => new object?[] { versions[Sx(row, 0)!], Sx(row, 1), Sx(row, 2), Sx(row, 3), Sx(row, 4) }), returnMap: false);
        var statuses = await CodeMapAsync(session, transaction, "ref", "ImplementationStatus", "ImplementationStatusId", "Code", cancellationToken);
        await loader.ReplaceAsync("ref", "SourceStatusLabel", null, ["FrameworkId", "BaselineSourceId", "SourceLabel", "ImplementationStatusId"],
            kb.Rows("statusLabels").Where(row => statuses.ContainsKey(Sx(row, 3)!) && (Sx(row, 0) is null || frameworks.ContainsKey(Sx(row, 0)!)))
                .Select(row => new object?[] { Lookup(frameworks, Sx(row, 0)), Lookup(baselineSources, Sx(row, 1)), Sx(row, 2), statuses[Sx(row, 3)!] }));

        // ----- Scoring model, enrichment, item scores -----
        Report(76, $"Writing the scoring model and {kb.Count("enrichment"):N0} enrichment values...");
        var attributes = await loader.UpsertAsync("score", "Attribute", "AttributeId", ["Code"], ["Name", "RatingScaleId", "DataTypeCode", "UnitCode", "IsCustomerSpecific", "Description"],
            kb.Rows("attributes").Select(row => new object?[] { Sx(row, 0), Sx(row, 1), Sx(row, 2) is { } scale ? scales[scale] : null, Sx(row, 3), Sx(row, 4), Bit(row, 5), Sx(row, 6) }));
        var models = await loader.UpsertAsync("score", "ScoringModel", "ScoringModelId", ["Code"], ["Name", "Version", "FormulaText", "IsDefault", "Description"],
            kb.Rows("scoringModels").Select(row => new object?[] { Sx(row, 0), Sx(row, 1), Sx(row, 2), Sx(row, 3), Bit(row, 4), Sx(row, 5) }));
        await loader.ReplaceAsync("score", "ScoringWeight", null, ["ScoringModelId", "AttributeId", "Weight", "TransformCode"],
            kb.Rows("scoringWeights").Select(row => new object?[] { models[Sx(row, 0)!], attributes[Sx(row, 1)!], Dx(row, 2), Sx(row, 3) }));
        var rules = await loader.UpsertAsync("score", "DerivationRule", "DerivationRuleId", ["Code"], ["AttributeId", "Priority", "AppliesToEntityTypeId", "RuleText", "RuleSql", "IsActive"],
            kb.Rows("derivationRules").Select(row => new object?[]
                { Sx(row, 0), attributes[Sx(row, 1)!], Ix(row, 2), Lookup(entityTypes, Sx(row, 3)), Sx(row, 4), Sx(row, 5), session.Bool(true) }));
        await loader.ReplaceAsync("score", "SourcePrecedence", null, ["AttributeId", "MappingSourceId", "Precedence"],
            kb.Rows("sourcePrecedence").Where(row => mappingSources.ContainsKey(Sx(row, 1)!))
                .Select(row => new object?[] { attributes[Sx(row, 0)!], mappingSources[Sx(row, 1)!], Ix(row, 2) }));
        var artifacts = await CodeMapAsync(session, transaction, "pol", "Artifact", "ArtifactId", "Code", cancellationToken);
        var tasks = await WbsTasksAsync(session, transaction, cancellationToken);
        int? Entity(JsonElement row, string kind)
        {
            var key = row[2];
            return (Sx(row, 1), kind) switch
            {
                ("Requirement", "Requirement") => Requirement(key[0].GetString(), key[1].GetString()),
                ("Recommendation", "Recommendation") => Recommendation(key[0].GetString(), key[1].GetString()),
                ("WbsTask", "WbsTask") => tasks.TryGetValue(Key(key[0].GetString(), key[1].GetString()), out var task) ? task : null,
                ("StandardItem", "StandardItem") => Lookup(items, key.GetString()),
                ("Artifact", "Artifact") => Lookup(artifacts, key.GetString()),
                _ => null
            };
        }

        var enrichment = kb.Rows("enrichment").Select(row => new object?[]
        {
            attributes[Sx(row, 0)!], Entity(row, "Requirement"), Entity(row, "Recommendation"), Entity(row, "StandardItem"), Entity(row, "Artifact"), Entity(row, "WbsTask"),
            Sx(row, 3), Dx(row, 4), Dx(row, 4) is { } number && Sx(row, 0) is "SCF_WEIGHT" or "LIKELIHOOD" ? Math.Min(100m, number * 10m) : null, AnyScaleValue(Sx(row, 5)),
            Lookup(mappingSources, Sx(row, 6)), Sx(row, 7), Sx(row, 8), Lookup(rules, Sx(row, 9)), session.Bool(true), today
        }).Where(row => row.Skip(1).Take(5).Any(value => value is not null));
        await loader.ReplaceAsync("score", "EnrichmentValue", null,
            ["AttributeId", "RequirementId", "RecommendationId", "StandardItemId", "ArtifactId", "WbsTaskId", "RawValue", "NumericValue", "NormalizedValue", "RatingScaleValueId",
             "MappingSourceId", "MethodCode", "ConfidenceCode", "DerivationRuleId", "IsCurrent", "EffectiveFrom"], enrichment);
        var now = timeProvider.GetUtcNow().UtcDateTime;
        await loader.ReplaceAsync("score", "ItemScore", null,
            ["ScoringModelId", "RequirementId", "RiskWeight", "Likelihood", "BusinessImpact", "RiskScore", "PriorityRank", "LowestConfidenceCode", "CalculatedAt"],
            kb.Rows("itemScores").Where(row => Entity(row, "Requirement") is not null).Select(row => new object?[]
                { models[Sx(row, 0)!], Entity(row, "Requirement"), Dx(row, 3), Dx(row, 4), Dx(row, 5), Dx(row, 6), Ix(row, 7), Sx(row, 8), now }));

        // ----- Delivery: complexity factors -----
        Report(92, "Writing complexity factors...");
        var factors = await loader.UpsertAsync("dlv", "ComplexityFactor", "ComplexityFactorId", ["Code"], ["Name", "Description"],
            kb.Rows("complexityFactors").Select(row => new object?[] { Sx(row, 0), Sx(row, 1), Sx(row, 2) }));
        await BulkUpdateAsync(session, transaction, session.Table("dlv", "WbsTask"), ["WbsTaskId"], ["ComplexityFactorId"],
            kb.Rows("taskFactors").Where(row => tasks.ContainsKey(Key(Sx(row, 0), Sx(row, 1))) && factors.ContainsKey(Sx(row, 2)!))
                .Select(row => new object?[] { factors[Sx(row, 2)!], tasks[Key(Sx(row, 0), Sx(row, 1))] }).ToList(), cancellationToken);

        // ----- Load log -----
        Report(96, "Recording the load...");
        var issueRows = kb.Rows("loadIssues").ToArray();
        var batch = await InsertBatchAsync(session, transaction, kb.Version, startedAt, timeProvider.GetUtcNow(), counts.Values.Sum(), issueRows.Length, cancellationToken);
        await BulkInsertAsync(session, transaction, session.Table("src", "LoadIssue"), ["LoadBatchId", "SeverityCode", "IssueCode", "Message"],
            issueRows.Select(row => new object?[] { batch, Sx(row, 0), Sx(row, 1), Sx(row, 2) is { Length: > 2000 } text ? text[..2000] : Sx(row, 2) }).ToList(), null, cancellationToken);
        counts["src.LoadIssue"] = issueRows.Length;

        var summary = $"phase 3 {kb.Version}: {counts.Values.Sum():N0} rows in {counts.Count} tables.";
        await SqlReferenceSeedStore.UpsertVersionAsync(session, transaction, Dataset, kb.Version, state.EmbeddedHash, counts.Values.Sum(), timeProvider.GetUtcNow(), summary,
            cancellationToken);
        await transaction.CommitAsync(cancellationToken);
        Report(100, "Licensing, threat coverage, tiers, scoring and guidance are loaded.");
        return new KnowledgeBaseLoadResult(false, $"phase 3 {kb.Version}", counts, started.Elapsed);
    }

    private static async Task<int> InsertBatchAsync(SqlSession session, DbTransaction transaction, string version, DateTimeOffset started, DateTimeOffset completed, int rows,
        int issues, CancellationToken cancellationToken)
    {
        var table = session.Table("src", "LoadBatch");
        var sql = $"INSERT INTO {table} (StartedAt, CompletedAt, LoadedBy, RowsRead, RowsLoaded, RowsRejected, StatusCode, ScriptVersion) " +
                  (session.Sqlite ? "VALUES (@s, @c, @by, @read, @loaded, 0, 'Succeeded', @v); SELECT last_insert_rowid();"
                      : "OUTPUT INSERTED.LoadBatchId VALUES (@s, @c, @by, @read, @loaded, 0, 'Succeeded', @v);");
        var result = await QueryAsync(session, transaction, sql, Parameters(("@s", started.UtcDateTime), ("@c", completed.UtcDateTime), ("@by", "Secure Plus knowledge base"),
            ("@read", rows), ("@loaded", rows), ("@v", $"phase 3 {version}; {issues} issue(s)")), cancellationToken);
        return Convert.ToInt32(result[0].Values.First(), CultureInfo.InvariantCulture);
    }

    private static async Task<Dictionary<string, int>> CodeMapAsync(SqlSession session, DbTransaction transaction, string schema, string table, string idColumn, string codeColumn,
        CancellationToken cancellationToken)
    {
        var map = new Dictionary<string, int>(KeyComparer);
        foreach (var row in await QueryAsync(session, transaction, $"SELECT {idColumn} AS Id, {codeColumn} AS Code FROM {session.Table(schema, table)};", null, cancellationToken))
            if (row["Code"] is string code) map[code] = Convert.ToInt32(row["Id"], CultureInfo.InvariantCulture);
        return map;
    }

    private static async Task<Dictionary<string, int>> RequirementsAsync(SqlSession session, DbTransaction transaction, CancellationToken cancellationToken)
    {
        var map = new Dictionary<string, int>(KeyComparer);
        foreach (var row in await QueryAsync(session, transaction,
                     $"SELECT f.Code AS F, r.RequirementCode AS R, r.RequirementId AS Id FROM {session.Table("fw", "Requirement")} AS r " +
                     $"JOIN {session.Table("fw", "FrameworkVersion")} AS v ON v.FrameworkVersionId = r.FrameworkVersionId JOIN {session.Table("fw", "Framework")} AS f ON f.FrameworkId = v.FrameworkId;",
                     null, cancellationToken))
            map[Key(row["F"], row["R"])] = Convert.ToInt32(row["Id"], CultureInfo.InvariantCulture);
        return map;
    }

    private static async Task<Dictionary<string, int>> FrameworkVersionsAsync(SqlSession session, DbTransaction transaction, CancellationToken cancellationToken)
    {
        var map = new Dictionary<string, int>(KeyComparer);
        foreach (var row in await QueryAsync(session, transaction,
                     $"SELECT f.Code AS F, MIN(v.FrameworkVersionId) AS Id FROM {session.Table("fw", "FrameworkVersion")} AS v JOIN {session.Table("fw", "Framework")} AS f ON f.FrameworkId = v.FrameworkId GROUP BY f.Code;",
                     null, cancellationToken))
            map[(string)row["F"]!] = Convert.ToInt32(row["Id"], CultureInfo.InvariantCulture);
        return map;
    }

    private static async Task<Dictionary<string, int>> RecommendationsAsync(SqlSession session, DbTransaction transaction, CancellationToken cancellationToken)
    {
        var map = new Dictionary<string, int>(KeyComparer);
        foreach (var row in await QueryAsync(session, transaction,
                     $"SELECT b.Code AS B, r.RecNumber AS N, r.RecommendationId AS Id FROM {session.Table("cfg", "Recommendation")} AS r JOIN {session.Table("cfg", "Baseline")} AS b ON b.BaselineId = r.BaselineId;",
                     null, cancellationToken))
            map[Key(row["B"], row["N"])] = Convert.ToInt32(row["Id"], CultureInfo.InvariantCulture);
        return map;
    }

    /// <summary>GDS standard items by item code (catalog items use the catalog control ID; checklist items CDC-...).</summary>
    private static async Task<Dictionary<string, int>> ItemsAsync(SqlSession session, DbTransaction transaction, CancellationToken cancellationToken)
    {
        var map = new Dictionary<string, int>(KeyComparer);
        foreach (var row in await QueryAsync(session, transaction,
                     $"SELECT ItemCode AS Code, StandardItemId AS Id FROM {session.Table("gds", "StandardItem")} WHERE ItemCode IS NOT NULL ORDER BY StandardItemId DESC;", null,
                     cancellationToken))
            map[(string)row["Code"]!] = Convert.ToInt32(row["Id"], CultureInfo.InvariantCulture);
        return map;
    }

    private static async Task<Dictionary<string, int>> WbsTasksAsync(SqlSession session, DbTransaction transaction, CancellationToken cancellationToken)
    {
        var map = new Dictionary<string, int>(KeyComparer);
        foreach (var row in await QueryAsync(session, transaction,
                     $"SELECT t.Code AS T, k.TaskCode AS C, k.WbsTaskId AS Id FROM {session.Table("dlv", "WbsTask")} AS k JOIN {session.Table("dlv", "WbsTemplate")} AS t ON t.WbsTemplateId = k.WbsTemplateId;",
                     null, cancellationToken))
            map[Key(row["T"], row["C"])] = Convert.ToInt32(row["Id"], CultureInfo.InvariantCulture);
        return map;
    }

    private static async Task<Dictionary<string, int>> AnswerOptionsAsync(SqlSession session, DbTransaction transaction, CancellationToken cancellationToken)
    {
        var map = new Dictionary<string, int>(KeyComparer);
        foreach (var row in await QueryAsync(session, transaction,
                     $"SELECT q.Code AS Q, o.OptionValue AS V, o.AnswerOptionId AS Id FROM {session.Table("eux", "AnswerOption")} AS o JOIN {session.Table("eux", "Question")} AS q ON q.QuestionId = o.QuestionId;",
                     null, cancellationToken))
            if (row["V"] is string value) map[Key(row["Q"], value)] = Convert.ToInt32(row["Id"], CultureInfo.InvariantCulture);
        return map;
    }

    private static DateTime? Date(string? text) =>
        DateTime.TryParseExact(text, ["yyyy-MM-dd", "yyyy-MM-ddTHH:mm:ss"], CultureInfo.InvariantCulture, DateTimeStyles.None, out var value) ? value : null;

